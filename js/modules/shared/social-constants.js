/**
 * js/modules/shared/social-constants.js - Social Domain Constants
 * Single source of truth for relationship types.
 *
 * Path: js/modules/shared/social-constants.js
 *
 * WHAT THIS OWNS:
 *   - The canonical relationship type registry (id, label, color,
 *     directional flag).
 *   - isDirectional / getLabel / getColor / isValidType /
 *     getDefaultTypeId / getRelationshipTypes.
 *   - The EXCLUSIVE_TYPES registry. A type is exclusive when a
 *     character can normally only be in one ongoing relationship
 *     of that type at a time. The romantic collision detector in
 *     social-core.js keys off this.
 *
 * WHAT THIS DOES NOT OWN:
 *   - Any relationship record shape. That is social-core.
 *   - Any display logic. social-views.
 *
 * EXCLUSIVE TYPES (this revision):
 *   A type is exclusive when two overlapping relationships of
 *   that type involving the same character are almost always a
 *   mistake. Romance is the obvious case: a character can be in
 *   exactly one ongoing romantic relationship at a time in the
 *   vast majority of narratives. Friendships, rivalries, mentors,
 *   and alliances are NOT exclusive — a character can have many
 *   of each. Familial is technically exclusive (you have one
 *   mother, one father) but the relationship records for
 *   parent/child use distinct clarifications and are generated by
 *   the child-creation flow, so treating familial as exclusive
 *   would produce noise on every half-sibling lookup. It is left
 *   out of the registry on purpose.
 *
 *   Extending the registry is a one-line change: add the type id
 *   with value `true`. The collision detector picks it up
 *   automatically.
 *
 * EXCLUSIVE TYPES DO NOT HARD-BLOCK:
 *   A detected overlap produces a warning banner in the form and
 *   a warning notification on save. It does NOT reject the save.
 *   The tool is for authoring fiction; some plots involve
 *   overlapping relationships, and a hard block would fight the
 *   user's intent. Warnings, not walls.
 *
 * DEPENDENCIES:
 *   None.
 */

(function() {
    'use strict';

    if (window.__socialConstantsLoaded) {
        return;
    }
    window.__socialConstantsLoaded = true;

    // ============================================================
    // RELATIONSHIP TYPES
    // ============================================================
    //
    // id          stable machine key (never change; data references it)
    // label       display name
    // color       CSS custom property reference, declared in shared.css
    // directional true when character1 -> character2 is meaningful
    //
    // The color field is a TOKEN REFERENCE, not a literal colour.
    // Every token is declared in css/shared.css under
    // --relationship-* with dark and light variants. Do NOT inline
    // hex literals here; add a token to shared.css and reference it
    // by name.

    var TYPES = [
        {
            id: 'familial',
            label: 'Familial',
            color: 'var(--relationship-familial)',
            directional: false
        },
        {
            id: 'professional',
            label: 'Professional',
            color: 'var(--relationship-professional)',
            directional: false
        },
        {
            id: 'romantic',
            label: 'Romantic',
            color: 'var(--relationship-romantic)',
            directional: false
        },
        {
            id: 'friendship',
            label: 'Friendship',
            color: 'var(--relationship-friendship)',
            directional: false
        },
        {
            id: 'mentor',
            label: 'Mentor',
            color: 'var(--relationship-mentor)',
            directional: true
        },
        {
            id: 'rivalry',
            label: 'Rivalry',
            color: 'var(--relationship-rivalry)',
            directional: false
        },
        {
            id: 'alliance',
            label: 'Alliance',
            color: 'var(--relationship-alliance)',
            directional: false
        },
        {
            id: 'other',
            label: 'Other',
            color: 'var(--relationship-other)',
            directional: false
        }
    ];

    // ============================================================
    // EXCLUSIVE TYPES
    // ============================================================
    //
    // Types that a character can normally only be in one ongoing
    // relationship of, at a time. Used by the collision detector.
    //
    // See the header note for why familial is NOT in this registry.

    var EXCLUSIVE_TYPES = {
        romantic: true
    };

    var DEFAULT_TYPE_ID = 'other';

    // ============================================================
    // LOOKUP TABLES
    // ============================================================

    var BY_ID = Object.create(null);
    TYPES.forEach(function(t) {
        BY_ID[t.id] = t;
    });

    // ============================================================
    // PUBLIC API
    // ============================================================

    function getRelationshipTypes() {
        return TYPES.map(function(t) {
            return {
                id: t.id,
                label: t.label,
                color: t.color,
                directional: t.directional === true
            };
        });
    }

    function getType(typeId) {
        if (!typeId) { return null; }
        var t = BY_ID[String(typeId)];
        if (!t) { return null; }
        return {
            id: t.id,
            label: t.label,
            color: t.color,
            directional: t.directional === true
        };
    }

    function isValidType(typeId) {
        if (!typeId) { return false; }
        return BY_ID[String(typeId)] !== undefined;
    }

    function getLabel(typeId) {
        var t = BY_ID[String(typeId)];
        return t ? t.label : String(typeId || 'Unknown');
    }

    function getColor(typeId) {
        var t = BY_ID[String(typeId)];
        return t ? t.color : 'var(--relationship-other)';
    }

    function isDirectional(typeId) {
        var t = BY_ID[String(typeId)];
        return t ? t.directional === true : false;
    }

    function getDefaultTypeId() {
        return DEFAULT_TYPE_ID;
    }

    /**
     * Is this type exclusive?
     *
     * An exclusive type is one a character can normally only be in
     * one ongoing relationship of, at a time. The romantic
     * collision detector uses this predicate to decide which
     * relationships to check for overlaps.
     *
     * Returns false for unknown / empty type ids.
     */
    function isExclusiveType(typeId) {
        if (!typeId) { return false; }
        return EXCLUSIVE_TYPES[String(typeId)] === true;
    }

    /**
     * Return the ids of every exclusive type, for callers that
     * need the set without re-declaring the registry.
     */
    function getExclusiveTypeIds() {
        return Object.keys(EXCLUSIVE_TYPES);
    }

    // ============================================================
    // EXPOSE
    // ============================================================

    window.SocialConstants = {
        // Registry
        getRelationshipTypes: getRelationshipTypes,
        getType: getType,

        // Type predicates / accessors
        isValidType: isValidType,
        getLabel: getLabel,
        getColor: getColor,
        isDirectional: isDirectional,
        getDefaultTypeId: getDefaultTypeId,

        // Exclusive type registry
        isExclusiveType: isExclusiveType,
        getExclusiveTypeIds: getExclusiveTypeIds
    };

})();
