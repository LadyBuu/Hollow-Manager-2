/**
 * modules/teams/team-core.js - Team Core
 * Canonical mutation API for teams.
 *
 * Path: js/modules/teams/team-core.js
 *
 * WHAT THIS OWNS:
 *   - Team CRUD (create, update, delete).
 *   - Member mutations: add interval, end interval, reopen interval,
 *     purge interval, remove member.
 *   - Batch member mutation (batchAddMembers).
 *   - Ranking mutations (add, remove).
 *   - Configuration (characterProvider injection).
 *   - The PERIODS model: validation, canonicalisation, and the
 *     legacy migration from nameHistory + scalars.
 *   - The `nameIsAuto` flag: accepted on create, preserved on
 *     update, carried through mutate. See NAME PROVENANCE below.
 *   - Cross-domain cascades:
 *       stripCharacterRefs      (character deletion)
 *       endStintsForCharacter   (character death, career transition)
 *       deleteTeam's mutate     (fires TournamentCore.stripTeamRefs,
 *                                MissionCascade.stripTeamRefs, and
 *                                AcademyCascade.teamDeleted)
 *
 * WHAT THIS DOES NOT OWN:
 *   - Public read APIs. Team reads go through TeamQueries.
 *   - Rendering, notifications, DOM.
 *   - saveData. The pipeline owns persistence.
 *   - The naming rule. TeamNaming owns the suffix grammar. This
 *     module accepts whatever periods TeamNaming writes; it does
 *     not compute the suffix.
 *   - The specialisation vocabulary. MissionConstants owns the
 *     mission type taxonomy. This module validates that a
 *     specialisation id is a known mission type via
 *     MissionConstants.isValidMissionType.
 *   - The mission cleanup details. MissionCascade.stripTeamRefs
 *     owns the reference model for team → mission.
 *   - The weeklyTeams cleanup details. AcademyCascade.teamDeleted
 *     owns the reference model for team → academy.weeklyTeams.
 *
 * NAME PROVENANCE (nameIsAuto):
 *   The `nameIsAuto` boolean records whether a team's current
 *   display name was generated by TeamNaming (auto) or typed by a
 *   user (manual). It exists to disambiguate the two places a
 *   team's name can be edited:
 *
 *     - the top-of-form field in the team form
 *     - the last period's name input in the periods editor
 *
 *   Without the flag, whichever side edited last wins on save,
 *   and the losing edit is silently discarded. With it, the
 *   reader/writer (team-events.js saveTeam) can decide:
 *
 *     nameIsAuto === true  → the periods array wins; the top
 *                            field is a display, and only
 *                            overrides if the user typed in it.
 *     nameIsAuto === false → the top field wins if dirty;
 *                            otherwise the periods array wins
 *                            as-edited.
 *
 *   WRITER RULES:
 *     createTeam                    → nameIsAuto: true (default)
 *     updateTeam with nameIsAuto    → nameIsAuto: <value>
 *     updateTeam without nameIsAuto → preserves the existing value
 *
 *   The migration (database.js v35) defaults existing teams to
 *   true. See the migration's comment for the reasoning.
 *
 * TYPE COMPARISONS:
 *   Every comparison of a team's `type` field in this module
 *   routes through TeamConstants.normalizeTeamType. In particular,
 *   endStintsForCharacter treats a legacy 'temporary' or
 *   'internship' team as 'professional', so a character's death
 *   cascade and career-transition cascade reach such teams.
 *
 * (rest of the file's header comment — periods model, mutation
 * contract, intervals model, death cascade, add-after-death
 * guard, naming hook, delete cascade — is unchanged from the
 * Phase G ship.)
 *
 * DEPENDENCIES (MANDATORY):
 *   - window.TeamConstants
 *   - window.IdUtils
 *   - window.MutationPipeline
 *   - window.ObjectUtils
 *   - characterProvider (injected via configure)
 *
 * DEPENDENCIES (LAZY, at call time):
 *   - window.MissionConstants    (specialisation id validation)
 *   - window.MissionCascade      (deleteTeam mission cleanup)
 *   - window.AcademyCascade      (deleteTeam weeklyTeams cleanup)
 *   - window.TournamentCore      (deleteTeam cascade; mandatory at
 *                                 that call, throws if unavailable)
 *   - window.TeamNaming          (post-member-add rename; optional)
 */

