/**
 * modules/tournaments/tournament-core.js - Tournament Core
 * CANONICAL mutation API for tournaments (tournament and round level).
 *
 * Path: js/modules/tournaments/tournament-core.js
 *
 * RESPONSIBILITIES:
 *   - Tournament CRUD (create, update, archive, purge)
 *   - Participant management (add, remove)
 *   - Round management (add, remove, reopen) — by stable round ID
 *   - Elimination week shift when endWeek changes (T8)
 *
 * NOT RESPONSIBILITIES:
 *   - Match-level mutations (TournamentMatches)
 *   - Tournament-level reads (TournamentQueries)
 *   - Cross-domain cascades (character deletion strips references
 *     through a dedicated cascade, not from here)
 *   - Lifecycle state machine (status is a soft label)
 *   - Public read surface (query via TournamentQueries)
 *
 * STATUS MODEL (SIMPLIFIED):
 *   Tournaments are RECORDS, not state machines. The status field is
 *   a soft label the user controls:
 *
 *     draft      — being set up
 *     active     — running
 *     completed  — done (can be reopened)
 *
 *   No operation is blocked by status. Any field can be updated at
 *   any time. Any participant can be added or removed at any time.
 *   Any round can be added at any time. Round removal is subject to
 *   the domain rule that a round with completed matches cannot be
 *   removed through the ordinary remove-round path.
 *
 *   There is no transitionStatus. Status is updated through
 *   updateTournament({ status: ... }) like any other field.
 *
 * ARCHIVE vs PURGE:
 *   Tournaments follow the same historical-preservation model as
 *   classes:
 *
 *     archiveTournament(id)
 *       Sets `archivedAt` and status 'completed'. The tournament and
 *       all its history remain intact. Archived tournaments are
 *       hidden from active selectors but stay queryable.
 *
 *     purgeTournament(id)
 *       Physically removes the tournament. Reverses every
 *       non-standalone character-side elimination keyed to it.
 *       Explicit destructive administration only.
 *
 *   The Academy UI uses archiveTournament. purgeTournament is not
 *   wired to the ordinary delete button.
 *
 * MUTATION CONTRACT:
 *   Every public mutation returns a Promise resolving to
 *   { success: boolean, data?: any, message?: string }.
 *
 * IDENTITY:
 *   Rounds carry stable IDs generated by TournamentMatches.buildRound.
 *   Round operations take IDs, not indices. roundNumber is positional
 *   (index + 1) and is recomputed after round removal.
 *
 * ELIMINATION REVERSAL:
 *   removeRound reverses eliminations produced by completed matches
 *   in the round, keyed by fromRoundId.
 *
 *   purgeTournament reverses every non-standalone character-side
 *   elimination keyed to the tournament.
 *
 *   Both run inside the same transaction as the structural mutation.
 *   If persistence fails, both roll back together.
 *
 * ELIMINATION WEEK SHIFT (T8):
 *   updateTournament shifts every tournament-driven elimination
 *   record for the tournament to the new endWeek, on both sides,
 *   when endWeek changes. The elimination week is derived from
 *   endWeek (see TournamentEliminationCascade.applyFailEliminations),
 *   so when endWeek moves, the eliminations move with it.
 *
 *   Standalone eliminations (Drop Out) are not touched.
 *
 *   The shift runs inside the same transaction as the endWeek
 *   update. If persistence fails, both roll back together.
 *
 *   The comparison is made entirely against the transaction snapshot:
 *   the pre-update endWeek is read from the snapshot immediately
 *   before the updates are applied. This makes the shift decision
 *   provably correct against the transaction's own view, rather than
 *   dependent on a preflight read of the live store.
 *
 * REOPEN SEMANTICS (v21):
 *   The model treats a completed match as committed: its eliminations
 *   reflect its results, and the results cannot be edited in place.
 *   When a user discovers a data-entry error or clicks Complete by
 *   mistake, they reopen:
 *
 *     TournamentMatches.reopenMatch(tournamentId, roundId, matchId)
 *       Per-match reopen. See tournament-matches.js.
 *
 *     reopenRound(tournamentId, roundId)
 *       Round-level reopen. Reverses every elimination produced by
 *       every match in the round, flips every match to 'pending',
 *       and sets the round's status to 'pending'. Results on each
 *       match are preserved. The round is now editable through the
 *       ordinary match-level path.
 *
 *   Reopen restores the invariant that eliminations match results,
 *   by removing the eliminations and letting the user fix the match
 *   results before completing again.
 *
 *   Round reopen does NOT recursively reopen matched rounds. It is
 *   one round at a time. If the user wants the whole tournament
 *   editable, they reopen each round.
 *
 *   Standalone eliminations are not touched by any reopen. Only
 *   eliminations whose provenance is this round (fromRoundId) are
 *   reversed.
 *
 * TRANSACTION VALIDATION:
 *   Pre-flight validation is for UX. Pipeline validation is for
 *   correctness. Every invariant is re-checked against the
 *   transaction snapshot.
 *
 * INTEGER PARSING:
 *   Positive-integer parsing goes through
 *   TournamentConstants.parsePositiveInteger, the single strict
 *   parser for the domain. This file has no local parser.
 *
 * DEPENDENCIES (MANDATORY):
 *   - window.TournamentConstants
 *   - window.TournamentSchema
 *   - window.TournamentRules
 *   - window.TournamentMatches
 *   - window.TournamentQueries
 *   - window.TournamentEliminationCascade
 *   - window.CalendarValidation
 *   - window.IdUtils
 *   - window.ObjectUtils
 *   - window.MutationPipeline
 */

