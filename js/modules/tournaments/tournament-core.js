    // UPDATE
    // ============================================================

    function updateTournament(id, updates) {
        if (!isObject(updates)) {
            return Promise.resolve(failure('Updates must be an object.'));
        }

        var updateKeys = Object.keys(updates);
        if (updateKeys.length === 0) {
            return Promise.resolve(failure('Updates are required.'));
        }

        var hasUndefined = updateKeys.some(function(key) {
            return updates[key] === undefined;
        });
        if (hasUndefined) {
            return Promise.resolve(
                failure('Updates cannot contain undefined values.')
            );
        }

        var tournament = getTournamentInternal(id);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var allowedKeys = [
            'name',
            'mode',
            'startWeek',
            'endWeek',
            'totalRounds',
            'status',
            'graduatingClassId',
            'classFilterEnabled'
        ];
        var unknownKeys = updateKeys.filter(function(key) {
            return allowedKeys.indexOf(key) === -1;
        });
        if (unknownKeys.length > 0) {
            return Promise.resolve(failure(
                'Unknown or non-updatable keys: ' +
                unknownKeys.join(', ')
            ));
        }

        if (updates.status !== undefined) {
            if (!Schema.isValidStatus(updates.status)) {
                return Promise.resolve(failure(
                    'Invalid status: ' + updates.status
                ));
            }
        }

        if (updates.name !== undefined &&
            !isNonEmptyString(updates.name)) {
            return Promise.resolve(failure(
                'Tournament name cannot be empty.'
            ));
        }

        if (updates.mode !== undefined &&
            !Schema.isValidMode(updates.mode)) {
            return Promise.resolve(failure(
                'Invalid mode: ' + updates.mode
            ));
        }

        var targetId = normaliseId(id);
        var updatesCopy = deepClone(updates);

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }

                var proposed = deepClone(current);
                var keys = Object.keys(updatesCopy);
                for (var i = 0; i < keys.length; i++) {
                    proposed[keys[i]] = updatesCopy[keys[i]];
                }

                if (updatesCopy.totalRounds !== undefined) {
                    var newTotal = parsePositiveInteger(
                        proposed.totalRounds
                    );
                    if (newTotal !== null &&
                        Array.isArray(current.rounds) &&
                        current.rounds.length > newTotal) {
                        return {
                            valid: false,
                            message:
                                'Cannot reduce total rounds below the ' +
                                'existing round count.'
                        };
                    }
                }

                if (updatesCopy.mode !== undefined &&
                    updatesCopy.mode !== current.mode) {
                    if (Array.isArray(current.participants) &&
                        current.participants.length > 0) {
                        return {
                            valid: false,
                            message:
                                'Cannot change mode while participants ' +
                                'exist.'
                        };
                    }
                }

                var validation = validateTournamentInSnapshot(
                    proposed,
                    { strict: false }
                );
                if (!validation.valid) {
                    return {
                        valid: false,
                        message: validation.errors.join('; ')
                    };
                }

                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }

                // ---- Capture pre-update endWeek FROM THE SNAPSHOT ----
                //
                // The shift decision (T8) must be made against the
                // transaction's own view. Reading the previous value
                // here, before applying the updates, ensures the
                // comparison is between the snapshot's current endWeek
                // and the proposed new endWeek. If a prior mutation in
                // the same transaction had already changed endWeek,
                // this read sees the change.
                //
                // The preflight read in getTournamentInternal is used
                // only for the "tournament exists" check and the
                // allowed-keys validation. It is NOT the source of the
                // shift comparison.
                var previousEndWeek = current.endWeek;

                var keys = Object.keys(updatesCopy);
                for (var i = 0; i < keys.length; i++) {
                    current[keys[i]] = deepClone(updatesCopy[keys[i]]);
                }

                // ---- T8: shift elimination weeks if endWeek changed ----
                //
                // The elimination week is derived from the tournament
                // endWeek (see TournamentEliminationCascade.
                // applyFailEliminations). When endWeek moves, every
                // tournament-driven elimination record for this
                // tournament moves with it, on both sides.
                //
                // Standalone eliminations (Drop Out) are not touched.
                //
                // The check is "endWeek was present in the update
                // AND the new value differs from the pre-update
                // value." Saving the same week again is a no-op.
                var shiftResult = null;
                if (updatesCopy.endWeek !== undefined) {
                    var newEndWeek = parseWeek(current.endWeek);
                    var oldEndWeek = parseWeek(previousEndWeek);
                    if (newEndWeek !== null &&
                        oldEndWeek !== null &&
                        newEndWeek !== oldEndWeek) {
                        shiftResult = EliminationCascade
                            .shiftTournamentEliminationWeeks(
                                appDataSnapshot,
                                targetId,
                                newEndWeek
                            );
                    }
                }

                return {
                    tournament: current,
                    id: targetId,
                    eliminationShift: shiftResult
                };
            },
            logMessage: function(result) {
                if (result && result.eliminationShift &&
                    result.eliminationShift.shifted > 0) {
                    return 'Updated tournament (shifted ' +
                        result.eliminationShift.shifted +
                        ' elimination week(s))';
                }
                return 'Updated tournament';
            },
            successMessage: 'Tournament updated successfully!',
            failureMessage: 'Failed to update tournament.'
        });
    }

