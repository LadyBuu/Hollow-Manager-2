/**
 * modules/tournaments/tournament-core.js - Tournament Core
 * CANONICAL mutation API for tournaments (tournament and round level).
 *
 * Path: js/modules/tournaments/tournament-core.js
 *
 * RESPONSIBILITIES:
 *   - Tournament CRUD (create, update, delete)
 *   - Participant management (add, remove)
 *   - Round management (add, remove) — by stable round ID
 *   - Tournament completion
 *   - Status transitions (canonical entry point)
 *   - Cross-domain cascade helper (stripCharacterRefs)
 *   - Synchronous reads (defensive copies)
 *
 * NOT RESPONSIBILITIES:
 *   - Match-level mutations (TournamentMatches)
 *   - Tournament-level reads for display (TournamentQueries)
 *
 * MUTATION CONTRACT:
 *   Every public mutation returns a Promise resolving to
 *   { success: boolean, data?: any, message?: string }.
 *
 *   Pre-flight reads against window.data provide immediate error
 *   messages. The pipeline's validate() callback re-reads from the
 *   snapshot and revalidates. The snapshot is authoritative.
 *
 * IDENTITY:
 *   Rounds carry stable IDs generated by TournamentSchema, via
 *   TournamentMatches.buildRound. Round operations take IDs, not
 *   indices. roundNumber is positional (index + 1) and is recomputed
 *   after round removal.
 *
 * STATUS TRANSITIONS:
 *   transitionStatus() is the single canonical entry point.
 *   completeTournament() is a thin wrapper.
 *
 *   A tournament can be marked completed when:
 *     - The lifecycle permits it (TournamentLifecycle.canCompleteTournament).
 *     - The domain is ready (TournamentRules.isReadyForCompletion).
 *     - Every round's status is 'completed'.
 *
 *   A winner is NOT required. A tournament may finish with zero, one,
 *   or many final passers.
 *
 * YEAR SEMANTICS:
 *   Tournaments are scoped to WEEKS (bounded 1-52), not years.
 *
 * DEPENDENCIES (MANDATORY):
 *   - window.TournamentSchema
 *   - window.TournamentConstants
 *   - window.TournamentLifecycle
 *   - window.TournamentRules
 *   - window.TournamentMatches
 *   - window.TournamentQueries
 *   - window.CharacterQueries
 *   - window.TeamQueries
 *   - window.CalendarValidation
 *   - window.IdUtils
 *   - window.ObjectUtils
 *   - window.MutationPipeline
 *
 * USAGE:
 *   var Core = window.TournamentCore;
 *
 *   Core.createTournament({ name: 'Spring Cup' }).then(function(result) {
 *       if (result.success) {
 *           var tournament = result.data;
 *       }
 *   });
 *
 *   Core.addRound('tourn_123', { matchSize: 2 }).then(function(result) {
 *       // result.data.round carries the new round, including its id
 *   });
 *
 *   Core.removeRound('tourn_123', 'round_abc').then(function(result) { ... });
 *
 *   Core.completeTournament('tourn_123').then(function(result) { ... });
 */

