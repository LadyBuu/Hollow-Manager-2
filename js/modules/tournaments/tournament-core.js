    function getTournamentInternal(id) {
        var normalisedId = normaliseId(id);
        if (normalisedId === null) {
            return null;
        }
        var data = getDataStore();
        if (!data || !Array.isArray(data.tournaments)) {
            return null;
        }
        for (var i = 0; i < data.tournaments.length; i++) {
            var t = data.tournaments[i];
            if (t && normaliseId(t.id) === normalisedId) {
                return t;
            }
        }
        return null;
    }

    // ============================================================
    // ID GENERATION
    // ============================================================

    function generateUniqueTournamentId(appData) {
        var attempts = 0;
        var maxAttempts = 10;
        var id;
        var generated = false;

        while (!generated && attempts < maxAttempts) {
            id = IdUtils.generateId('tourn');
            attempts++;

            var normalisedId_ = normaliseId(id);
            if (normalisedId_ === null) {
                continue;
            }

            var collision = Array.isArray(appData.tournaments) &&
                appData.tournaments.some(function(t) {
                    return t && normaliseId(t.id) === normalisedId_;
                });

            if (!collision) {
                generated = true;
            }
        }

        if (!generated) {
            return null;
        }
        return normaliseId(id);
    }

