    function addRound(tournamentId, roundData) {
        var tournament = getTournamentInternal(tournamentId);
        if (!tournament || !Array.isArray(tournament.rounds)) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var matchSize = 2;
        var matchType = 'group_exam';
        var isPairExam = false;

        if (roundData && typeof roundData === 'object') {
            if (roundData.matchSize !== undefined) {
                var size = parsePositiveInteger(
                    roundData.matchSize
                );
                if (size === null || size < 2) {
                    return Promise.resolve(failure(
                        'Match size must be an integer >= 2.'
                    ));
                }
                matchSize = size;
            }

            if (roundData.matchType !== undefined) {
                if (!Schema.isValidMatchType(roundData.matchType)) {
                    return Promise.resolve(failure(
                        'Invalid match type: ' + roundData.matchType
                    ));
                }
                matchType = roundData.matchType;
            }

            if (roundData.isPairExam === true) {
                if (matchType !== 'group_exam') {
                    return Promise.resolve(failure(
                        'Pair exams require match type "group_exam".'
                    ));
                }
                isPairExam = true;
                matchSize = 2;
            }
        }

        var ruleCheck = Rules.validateRoundAddition(tournament, {
            matchSize: matchSize,
            matchType: matchType,
            isPairExam: isPairExam
        });
        if (!ruleCheck.valid) {
            return Promise.resolve(failure(ruleCheck.message));
        }

        var roundNumber = tournament.rounds.length + 1;
        var round = Matches.buildRound({
            matchSize: matchSize,
            matchType: matchType,
            roundNumber: roundNumber,
            isPairExam: isPairExam
        });

        if (!round || !normaliseId(round.id)) {
            return Promise.resolve(
                failure('Failed to build round with a stable ID.')
            );
        }

        var roundCopy = deepClone(round);
        var targetTournamentId = normaliseId(tournamentId);

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                if (!Array.isArray(current.rounds)) {
                    current.rounds = [];
                }
                current.rounds.push(roundCopy);
                return { round: roundCopy, roundId: roundCopy.id };
            },
            logMessage: 'Added round to tournament: ' +
                (tournament.name || targetTournamentId),
            successMessage: 'Round added successfully!',
            failureMessage: 'Failed to add round.'
        });
    }

    function removeRound(tournamentId, roundId) {
        var normalisedRoundId = normaliseId(roundId);
        if (normalisedRoundId === null) {
            return Promise.resolve(failure('Round ID is required.'));
        }

        var tournament = getTournamentInternal(tournamentId);
        if (!tournament || !Array.isArray(tournament.rounds)) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundByIdInternal(
            tournament,
            normalisedRoundId
        );
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        var ruleCheck = Rules.validateRoundRemoval(
            tournament,
            Schema.findRoundIndexById(tournament, normalisedRoundId)
        );
        if (!ruleCheck.valid) {
            return Promise.resolve(failure(ruleCheck.message));
        }

        var targetTournamentId = normaliseId(tournamentId);
        var roundDisplayNumber = round.roundNumber;

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current || !Array.isArray(current.rounds)) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                if (!Schema.findRoundByIdInternal(
                    current,
                    normalisedRoundId
                )) {
                    return {
                        valid: false,
                        message: 'Round no longer exists.'
                    };
                }
                var idx = Schema.findRoundIndexById(
                    current,
                    normalisedRoundId
                );
                var removalCheck = Rules.validateRoundRemoval(
                    current,
                    idx
                );
                if (!removalCheck.valid) {
                    return {
                        valid: false,
                        message: removalCheck.message
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current || !Array.isArray(current.rounds)) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }

                // Reverse eliminations BEFORE splicing the round.
                var reversal = EliminationCascade
                    .reverseRoundEliminations(
                        appDataSnapshot,
                        current,
                        normalisedRoundId
                    );

                var idx = Schema.findRoundIndexById(
                    current,
                    normalisedRoundId
                );
                if (idx === -1) {
                    throw new Error(
                        'Round not found in data store.'
                    );
                }

                current.rounds.splice(idx, 1);

                // Recompute roundNumber positionally.
                for (var i = 0; i < current.rounds.length; i++) {
                    current.rounds[i].roundNumber = i + 1;
                }

                return {
                    roundId: normalisedRoundId,
                    roundDisplayNumber: roundDisplayNumber,
                    eliminationsReversed: reversal.reversed,
                    reversedCharacterIds: reversal.characterIds
                };
            },
            logMessage: function(result) {
                if (result && result.eliminationsReversed > 0) {
                    return 'Removed round ' + roundDisplayNumber +
                        ' from tournament: ' +
                        (tournament.name || targetTournamentId) +
                        ' (reversed ' + result.eliminationsReversed +
                        ' elimination(s))';
                }
                return 'Removed round ' + roundDisplayNumber +
                    ' from tournament: ' +
                    (tournament.name || targetTournamentId);
            },
            successMessage: 'Round removed successfully!',
            failureMessage: 'Failed to remove round.'
        });
    }

    // ============================================================
    // ROUND REOPEN (v21)
    // ============================================================

    /**
     * Reopen a round so every match in it can be edited.
     *
     * SEMANTICS:
     *   - Reverses every elimination produced by every match in the
     *     round, via the cascade's reverseRoundEliminations (keyed
     *     by fromRoundId).
     *   - Flips every match in the round to 'pending'. Results on
     *     each match are preserved. The form pre-populates when the
     *     user reopens a match for editing.
     *   - Sets the round's status to 'pending'.
     *   - Standalone eliminations are not touched. Eliminations
     *     produced by other rounds are not touched.
     *
     * The round is now editable through the ordinary match-level
     * path. When the user is done editing, each match is completed
     * individually, or the round is completed when all its matches
     * are complete.
     *
     * @param {string} tournamentId
     * @param {string} roundId
     * @returns {Promise<{success, data?, message?}>}
     */
    function reopenRound(tournamentId, roundId) {
        var normalisedRoundId = normaliseId(roundId);
        if (normalisedRoundId === null) {
            return Promise.resolve(failure('Round ID is required.'));
        }

        var tournament = getTournamentInternal(tournamentId);
        if (!tournament || !Array.isArray(tournament.rounds)) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundByIdInternal(
            tournament,
            normalisedRoundId
        );
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        var targetTournamentId = normaliseId(tournamentId);
        var roundDisplayNumber = round.roundNumber;
        var matchCount = Array.isArray(round.matches)
            ? round.matches.length
            : 0;

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current || !Array.isArray(current.rounds)) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                if (!Schema.findRoundByIdInternal(
                    current,
                    normalisedRoundId
                )) {
                    return {
                        valid: false,
                        message: 'Round no longer exists.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current || !Array.isArray(current.rounds)) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }

                var liveRound = Schema.findRoundByIdInternal(
                    current,
                    normalisedRoundId
                );
                if (!liveRound) {
                    throw new Error(
                        'Round not found in data store.'
                    );
                }

                // ---- Reverse eliminations keyed to this round ----
                var reversal = EliminationCascade
                    .reverseRoundEliminations(
                        appDataSnapshot,
                        current,
                        normalisedRoundId
                    );

                // ---- Flip every match in the round to pending ----
                var reopenedCount = 0;
                if (Array.isArray(liveRound.matches)) {
                    for (var i = 0; i < liveRound.matches.length; i++) {
                        var m = liveRound.matches[i];
                        if (!m) { continue; }
                        if (m.status !== 'pending') {
                            m.status = 'pending';
                            reopenedCount++;
                        }
                    }
                }

                // ---- Reset the round's own status ----
                liveRound.status = 'pending';

                return {
                    roundId: normalisedRoundId,
                    roundDisplayNumber: roundDisplayNumber,
                    matchesReopened: reopenedCount,
                    eliminationsReversed: reversal.reversed,
                    reversedCharacterIds: reversal.characterIds
                };
            },
            logMessage: function(result) {
                var parts = [];
                if (result.matchesReopened > 0) {
                    parts.push(result.matchesReopened + ' match(es)');
                }
                if (result.eliminationsReversed > 0) {
                    parts.push(result.eliminationsReversed +
                        ' elimination(s)');
                }
                var suffix = parts.length > 0
                    ? ' (' + parts.join(', ') + ')'
                    : '';
                return 'Reopened round ' + roundDisplayNumber +
                    ' of tournament: ' +
                    (tournament.name || targetTournamentId) + suffix;
            },
            successMessage: 'Round reopened. Matches are editable.',
            failureMessage: 'Failed to reopen round.'
        });
    }

