    function archiveTournament(id) {
        var normalisedId_ = normaliseId(id);
        if (normalisedId_ === null) {
            return Promise.resolve(
                failure('Tournament ID is required.')
            );
        }

        var tournament = getTournamentInternal(normalisedId_);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        if (tournament.archivedAt) {
            return Promise.resolve(failure(
                'Tournament is already archived.'
            ));
        }

        var name = tournament.name || 'Unknown';

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    normalisedId_
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                if (current.archivedAt) {
                    return {
                        valid: false,
                        message: 'Tournament is already archived.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    normalisedId_
                );
                if (!current) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }

                current.archivedAt = new Date().toISOString();
                current.status = 'completed';

                return {
                    id: normalisedId_,
                    archivedAt: current.archivedAt
                };
            },
            logMessage: 'Archived tournament: ' + name,
            successMessage: 'Tournament archived.',
            failureMessage: 'Failed to archive tournament.'
        });
    }

    function purgeTournament(id) {
        var normalisedId_ = normaliseId(id);
        if (normalisedId_ === null) {
            return Promise.resolve(
                failure('Tournament ID is required.')
            );
        }

        var tournament = getTournamentInternal(normalisedId_);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var name = tournament.name || 'Unknown';

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var target = findTournamentInSnapshot(
                    appDataSnapshot,
                    normalisedId_
                );
                if (!target) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                if (!Array.isArray(appDataSnapshot.tournaments)) {
                    throw new Error(
                        'Tournament store is not available.'
                    );
                }

                // Reverse character-side eliminations BEFORE the
                // tournament record is spliced out.
                var reversal = EliminationCascade
                    .reverseTournamentEliminations(
                        appDataSnapshot,
                        normalisedId_
                    );

                var idx = -1;
                for (var i = 0;
                     i < appDataSnapshot.tournaments.length;
                     i++) {
                    if (normaliseId(
                        appDataSnapshot.tournaments[i].id
                    ) === normalisedId_) {
                        idx = i;
                        break;
                    }
                }
                if (idx === -1) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                appDataSnapshot.tournaments.splice(idx, 1);

                return {
                    id: normalisedId_,
                    eliminationsReversed: reversal.reversed,
                    reversedCharacterIds: reversal.characterIds
                };
            },
            logMessage: function(result) {
                if (result && result.eliminationsReversed > 0) {
                    return 'Purged tournament: ' + name +
                        ' (reversed ' + result.eliminationsReversed +
                        ' elimination(s))';
                }
                return 'Purged tournament: ' + name;
            },
            successMessage: 'Tournament purged.',
            failureMessage: 'Failed to purge tournament.'
        });
    }

