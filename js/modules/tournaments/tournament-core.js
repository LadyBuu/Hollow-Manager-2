    function createTournament(data) {
        if (!isObject(data)) {
            return Promise.resolve(
                failure('Tournament data is required.')
            );
        }
        if (!isNonEmptyString(data.name)) {
            return Promise.resolve(
                failure('Tournament name is required.')
            );
        }
        var name = data.name.trim();

        var mode = data.mode || 'teams';
        if (!Schema.isValidMode(mode)) {
            return Promise.resolve(failure('Invalid mode: ' + mode));
        }

        var startWeek = data.startWeek !== undefined ? data.startWeek : 1;
        var parsedStart = parseWeek(startWeek);
        if (parsedStart === null) {
            return Promise.resolve(failure('Invalid start week.'));
        }

        var endWeek = data.endWeek !== undefined ? data.endWeek : 52;
        var parsedEnd = parseWeek(endWeek);
        if (parsedEnd === null) {
            return Promise.resolve(failure('Invalid end week.'));
        }

        if (parsedStart > parsedEnd) {
            return Promise.resolve(
                failure('Start week cannot be after end week.')
            );
        }

        var totalRounds = data.totalRounds !== undefined
            ? data.totalRounds
            : 1;
        var parsedRounds = parsePositiveInteger(totalRounds);
        if (parsedRounds === null) {
            return Promise.resolve(failure('Invalid total rounds.'));
        }

        var status = data.status || 'draft';
        if (!Schema.isValidStatus(status)) {
            return Promise.resolve(failure('Invalid status: ' + status));
        }

        var graduatingClassId = data.graduatingClassId !== undefined
            ? normaliseId(data.graduatingClassId)
            : null;

        var classFilterEnabled = data.classFilterEnabled !== false;

        var appData = getDataStore();
        var id = generateUniqueTournamentId(appData);
        if (id === null) {
            return Promise.resolve(
                failure('Failed to generate a unique tournament ID.')
            );
        }

        var newTournament = {
            id: id,
            name: name,
            mode: mode,
            startWeek: parsedStart,
            endWeek: parsedEnd,
            totalRounds: parsedRounds,
            status: status,
            participants: [],
            rounds: [],
            eliminations: [],
            winner: null,
            createdAt: new Date().toISOString(),
            _schemaVersion: Schema.SCHEMA_VERSION,
            graduatingClassId: graduatingClassId,
            classFilterEnabled: classFilterEnabled
        };

        var validation = validateTournamentInternal(newTournament, true);
        if (!validation.valid) {
            return Promise.resolve(
                failure(validation.errors.join('; '))
            );
        }

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                if (!appDataSnapshot ||
                    !Array.isArray(appDataSnapshot.tournaments)) {
                    return {
                        valid: false,
                        message: 'Tournament store is not available.'
                    };
                }
                var collision = appDataSnapshot.tournaments.some(
                    function(t) {
                        return t && normaliseId(t.id) === id;
                    }
                );
                if (collision) {
                    return {
                        valid: false,
                        message: 'Tournament ID collision.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                if (!Array.isArray(appDataSnapshot.tournaments)) {
                    appDataSnapshot.tournaments = [];
                }
                appDataSnapshot.tournaments.push(deepClone(newTournament));
                return { tournament: newTournament, id: id };
            },
            logMessage: 'Created tournament: ' + name,
            successMessage: 'Tournament created successfully!',
            failureMessage: 'Failed to create tournament.'
        });
    }

    /**
     * Update an existing tournament.
     *
     * UPDATABLE FIELDS:
     *   name, mode, startWeek, endWeek, totalRounds, status,
     *   graduatingClassId, classFilterEnabled
     *
     * No status gate. Any field can be updated at any time.
     * Status is a soft label, so it can be changed here too.
     */
    function updateTournament(id, updates) {
        if (!isObject(updates)) {
            return Promise.resolve(
                failure('Updates must be an object.')
            );
        }

        var updateKeys = Object.keys(updates);
        if (updateKeys.length === 0) {
            return Promise.resolve(failure('Updates are required.'));
        }

        var hasUndefined = updateKeys.some(function(key) {
            return updates[key] === undefined;
        });
        if (hasUndefined) {
            return Promise.resolve(
                failure('Updates cannot contain undefined values.')
            );
        }

        var tournament = getValidatedTournament(id, false);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var allowedKeys = [
            'name',
            'mode',
            'startWeek',
            'endWeek',
            'totalRounds',
            'status',
            'graduatingClassId',
            'classFilterEnabled'
        ];
        var unknownKeys = updateKeys.filter(function(key) {
            return allowedKeys.indexOf(key) === -1;
        });
        if (unknownKeys.length > 0) {
            return Promise.resolve(failure(
                'Unknown or non-updatable keys: ' +
                unknownKeys.join(', ')
            ));
        }

        if (updates.status !== undefined) {
            if (!Schema.isValidStatus(updates.status)) {
                return Promise.resolve(failure(
                    'Invalid status: ' + updates.status
                ));
            }
        }

        var proposed = Object.assign({}, tournament);
        Object.keys(updates).forEach(function(key) {
            if (updates[key] !== undefined) {
                proposed[key] = updates[key];
            }
        });

        if (updates.totalRounds !== undefined) {
            var newTotal = parsePositiveInteger(proposed.totalRounds);
            if (newTotal !== null &&
                Array.isArray(tournament.rounds) &&
                tournament.rounds.length > newTotal) {
                return Promise.resolve(failure(
                    'Cannot reduce total rounds below the existing ' +
                    'round count.'
                ));
            }
        }

        if (updates.mode !== undefined &&
            updates.mode !== tournament.mode) {
            if (Array.isArray(tournament.participants) &&
                tournament.participants.length > 0) {
                return Promise.resolve(failure(
                    'Cannot change mode while participants exist.'
                ));
            }
        }

        var validation = validateTournamentInternal(proposed, false);
        if (!validation.valid) {
            return Promise.resolve(
                failure(validation.errors.join('; '))
            );
        }

        var targetId = normaliseId(id);

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var snapshot = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!snapshot) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var target = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!target) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                allowedKeys.forEach(function(key) {
                    if (updates[key] === undefined) { return; }
                    target[key] = proposed[key];
                });
                return { tournament: target, id: targetId };
            },
            logMessage: 'Updated tournament: ' + proposed.name,
            successMessage: 'Tournament updated successfully!',
            failureMessage: 'Failed to update tournament.'
        });
    }

    /**
     * Delete a tournament permanently.
     *
     * ELIMINATION REVERSAL:
     *   Before the tournament is spliced out, every non-standalone
     *   character-side elimination keyed to it is removed. Standalone
     *   eliminations (standalone: true, tournamentId: null) are not
     *   touched. The tournament's own eliminations[] disappears with
     *   the record, so only the character side needs explicit cleanup.
     *
     *   The reversal runs inside the same transaction as the removal.
     *   If persistence fails, both roll back together.
     */
    function deleteTournament(id) {
        var normalisedId_ = normaliseId(id);
        if (normalisedId_ === null) {
            return Promise.resolve(
                failure('Tournament ID is required.')
            );
        }

        var tournament = getValidatedTournament(normalisedId_, false);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var tournamentName = tournament.name || 'Unknown';

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var target = findTournamentInSnapshot(
                    appDataSnapshot,
                    normalisedId_
                );
                if (!target) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                if (!Array.isArray(appDataSnapshot.tournaments)) {
                    throw new Error('Tournament store is not available.');
                }

                // ---- Reverse character-side eliminations ----
                // Runs BEFORE the splice so the reversal sees a
                // consistent snapshot. The tournament record is about
                // to disappear; its eliminations[] go with it. Only
                // the character side needs explicit cleanup.
                var reversal = EliminationCascade
                    .reverseTournamentEliminations(
                        appDataSnapshot,
                        normalisedId_
                    );

                var idx = -1;
                for (var i = 0; i < appDataSnapshot.tournaments.length; i++) {
                    if (normaliseId(appDataSnapshot.tournaments[i].id) ===
                        normalisedId_) {
                        idx = i;
                        break;
                    }
                }
                if (idx === -1) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                appDataSnapshot.tournaments.splice(idx, 1);

                return {
                    id: normalisedId_,
                    eliminationsReversed: reversal.reversed,
                    reversedCharacterIds: reversal.characterIds
                };
            },
            logMessage: function(result) {
                if (result && result.eliminationsReversed > 0) {
                    return 'Deleted tournament: ' + tournamentName +
                        ' (reversed ' + result.eliminationsReversed +
                        ' elimination(s))';
                }
                return 'Deleted tournament: ' + tournamentName;
            },
            successMessage: 'Tournament deleted successfully!',
            failureMessage: 'Failed to delete tournament.'
        });
    }

