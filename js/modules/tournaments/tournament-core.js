    function createTournament(data) {
        if (!isObject(data)) {
            return Promise.resolve(
                failure('Tournament data is required.')
            );
        }
        if (!isNonEmptyString(data.name)) {
            return Promise.resolve(
                failure('Tournament name is required.')
            );
        }
        var name = data.name.trim();

        if (!Schema.isValidMode(data.mode)) {
            return Promise.resolve(failure(
                'Tournament mode is required and must be one of: ' +
                Schema.VALID_MODES.join(', ') + '.'
            ));
        }
        var mode = data.mode;

        var startWeek = data.startWeek !== undefined
            ? data.startWeek
            : 1;
        var parsedStart = parseWeek(startWeek);
        if (parsedStart === null) {
            return Promise.resolve(failure('Invalid start week.'));
        }

        var endWeek = data.endWeek !== undefined
            ? data.endWeek
            : Schema.MAX_WEEK;
        var parsedEnd = parseWeek(endWeek);
        if (parsedEnd === null) {
            return Promise.resolve(failure('Invalid end week.'));
        }

        if (parsedStart > parsedEnd) {
            return Promise.resolve(
                failure('Start week cannot be after end week.')
            );
        }

        var totalRounds = data.totalRounds !== undefined
            ? data.totalRounds
            : 1;
        var parsedRounds = parsePositiveInteger(totalRounds);
        if (parsedRounds === null) {
            return Promise.resolve(failure('Invalid total rounds.'));
        }

        var status = data.status !== undefined
            ? data.status
            : 'draft';
        if (!Schema.isValidStatus(status)) {
            return Promise.resolve(failure('Invalid status: ' + status));
        }

        var graduatingClassId = data.graduatingClassId !== undefined
            ? normaliseId(data.graduatingClassId)
            : null;

        var classFilterEnabled = data.classFilterEnabled === true;

        var appData = getDataStore();
        if (!appData || !Array.isArray(appData.tournaments)) {
            return Promise.resolve(failure(
                'Tournament store is not available.'
            ));
        }

        var id = generateUniqueTournamentId(appData);
        if (id === null) {
            return Promise.resolve(
                failure('Failed to generate a unique tournament ID.')
            );
        }

        var now = new Date().toISOString();

        var newTournament = {
            id: id,
            name: name,
            mode: mode,
            startWeek: parsedStart,
            endWeek: parsedEnd,
            totalRounds: parsedRounds,
            status: status,
            participants: [],
            rounds: [],
            eliminations: [],
            graduatingClassId: graduatingClassId,
            classFilterEnabled: classFilterEnabled,
            createdAt: now,
            archivedAt: null,
            _schemaVersion: Schema.SCHEMA_VERSION
        };

        var validation = validateTournamentInSnapshot(newTournament, {
            strict: true
        });
        if (!validation.valid) {
            return Promise.resolve(
                failure(validation.errors.join('; '))
            );
        }

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                if (!appDataSnapshot ||
                    !Array.isArray(appDataSnapshot.tournaments)) {
                    return {
                        valid: false,
                        message: 'Tournament store is not available.'
                    };
                }
                var collision = appDataSnapshot.tournaments.some(
                    function(t) {
                        return t && normaliseId(t.id) === id;
                    }
                );
                if (collision) {
                    return {
                        valid: false,
                        message: 'Tournament ID collision.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                if (!Array.isArray(appDataSnapshot.tournaments)) {
                    appDataSnapshot.tournaments = [];
                }
                appDataSnapshot.tournaments.push(deepClone(newTournament));
                return { tournament: newTournament, id: id };
            },
            logMessage: 'Created tournament: ' + name,
            successMessage: 'Tournament created successfully!',
            failureMessage: 'Failed to create tournament.'
        });
    }

