    /**
     * Get the last round whose status is not 'completed'.
     * Returns null when every round is complete, or the tournament
     * has no rounds.
     */
    function getActiveRound(tournamentId) {
        var tournament = getTournamentInternal(tournamentId);
        if (!tournament || !Array.isArray(tournament.rounds)) {
            return null;
        }
        for (var i = tournament.rounds.length - 1; i >= 0; i--) {
            var round = tournament.rounds[i];
            if (round && round.status !== 'completed') {
                return deepClone(round);
            }
        }
        return null;
    }

    /**
     * Is the tournament complete?
     *
     * A completed tournament is one whose status is 'completed' and
     * whose every round has a status of 'completed'.
     *
     * A winner is NOT required. A tournament may finish with zero,
     * one, or many final passers.
     */
    function isComplete(tournamentId) {
        var tournament = getTournamentInternal(tournamentId);
        if (!tournament) {
            return false;
        }

        if (tournament.status !== 'completed') {
            return false;
        }

        if (!Array.isArray(tournament.rounds) ||
            tournament.rounds.length === 0) {
            return false;
        }

        return tournament.rounds.every(function(r) {
            return r && r.status === 'completed';
        });
    }

