    function addRound(tournamentId, roundData) {
        var tournament = getValidatedTournament(tournamentId, false);
        if (!tournament || !Array.isArray(tournament.rounds)) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        // No hard cap. The user can exceed totalRounds if they want.
        // (totalRounds is a soft planning hint, not an invariant.)

        var matchSize = 2;
        var matchType = 'group_exam';
        var isPairExam = false;

        if (roundData && typeof roundData === 'object') {
            if (roundData.matchSize !== undefined) {
                var size = parsePositiveInteger(roundData.matchSize);
                if (size === null || size < 2) {
                    return Promise.resolve(failure(
                        'Match size must be an integer >= 2.'
                    ));
                }
                matchSize = size;
            }

            if (roundData.matchType !== undefined) {
                if (!Schema.isValidMatchType(roundData.matchType)) {
                    return Promise.resolve(failure(
                        'Invalid match type: ' + roundData.matchType
                    ));
                }
                matchType = roundData.matchType;
            }

            if (roundData.isPairExam === true) {
                isPairExam = true;
                if (matchType !== 'group_exam') {
                    matchType = 'group_exam';
                }
                matchSize = 2;
            }
        }

        var participants = [];
        if (Array.isArray(tournament.participants)) {
            for (var i = 0; i < tournament.participants.length; i++) {
                var p = tournament.participants[i];
                if (p && !Schema.isParticipantEliminated(tournament, p.id)) {
                    participants.push(p.id);
                }
            }
        }

        var roundNumber = tournament.rounds.length + 1;
        var round = Matches.buildRound({
            matchSize: matchSize,
            matchType: matchType,
            roundNumber: roundNumber,
            isPairExam: isPairExam
        }, participants);

        if (!round || !normaliseId(round.id)) {
            return Promise.resolve(
                failure('Failed to build round with a stable ID.')
            );
        }

        var roundCopy = deepClone(round);
        var targetTournamentId = normaliseId(tournamentId);
        var promoteToActive = tournament.status === 'draft';
        var expectedStatus = tournament.status;

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                // Only enforce status stability when we're about to
                // change it ourselves (draft → active).
                if (promoteToActive && current.status !== expectedStatus) {
                    return {
                        valid: false,
                        message:
                            'Tournament status has changed since this ' +
                            'request was made.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                if (!Array.isArray(current.rounds)) {
                    current.rounds = [];
                }
                current.rounds.push(roundCopy);
                if (promoteToActive) {
                    current.status = 'active';
                }
                return { round: roundCopy, roundId: roundCopy.id };
            },
            logMessage: 'Added round to tournament: ' +
                (tournament.name || targetTournamentId),
            successMessage: 'Round added successfully!',
            failureMessage: 'Failed to add round.'
        });
    }

    /**
     * Remove a round from a tournament.
     *
     * No status gate. After removal, the remaining rounds' roundNumber
     * fields are recomputed positionally. Round IDs are preserved.
     *
     * The tournament status is NOT auto-reset when the last round is
     * removed. Status is the user's label.
     *
     * ELIMINATION REVERSAL:
     *   Every completed match in the round may have produced
     *   eliminations. Those eliminations are reversed BEFORE the
     *   round is spliced out. The reversal is keyed by
     *   (tournamentId, fromRoundId) on both sides. Standalone
     *   eliminations and legacy eliminations without provenance are
     *   not touched.
     *
     *   The reversal runs inside the same transaction as the removal.
     *   If persistence fails, both roll back together.
     */
    function removeRound(tournamentId, roundId) {
        var normalisedRoundId = normaliseId(roundId);
        if (normalisedRoundId === null) {
            return Promise.resolve(
                failure('Round ID is required.')
            );
        }

        var tournament = getValidatedTournament(tournamentId, false);
        if (!tournament || !Array.isArray(tournament.rounds)) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundById(tournament, normalisedRoundId);
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        // No status gate. No lifecycle check.

        var targetTournamentId = normaliseId(tournamentId);
        var roundDisplayNumber = round.roundNumber || 0;

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current || !Array.isArray(current.rounds)) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                if (!Schema.findRoundById(current, normalisedRoundId)) {
                    return {
                        valid: false,
                        message: 'Round no longer exists.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetTournamentId
                );
                if (!current || !Array.isArray(current.rounds)) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }

                // ---- Reverse eliminations produced by this round ----
                // Runs BEFORE the splice. The reversal sees the round
                // still in place, which is fine: it filters by
                // fromRoundId, not by round position.
                var reversal = EliminationCascade
                    .reverseRoundEliminations(
                        appDataSnapshot,
                        current,
                        normalisedRoundId
                    );

                var idx = Schema.findRoundIndexById(
                    current,
                    normalisedRoundId
                );
                if (idx === -1) {
                    throw new Error(
                        'Round not found in data store.'
                    );
                }

                current.rounds.splice(idx, 1);

                // Recompute roundNumber positionally. IDs are preserved.
                for (var i = 0; i < current.rounds.length; i++) {
                    current.rounds[i].roundNumber = i + 1;
                }

                // No automatic status change. The user decides.

                return {
                    roundId: normalisedRoundId,
                    roundDisplayNumber: roundDisplayNumber,
                    eliminationsReversed: reversal.reversed,
                    reversedCharacterIds: reversal.characterIds
                };
            },
            logMessage: function(result) {
                if (result && result.eliminationsReversed > 0) {
                    return 'Removed round ' + roundDisplayNumber +
                        ' from tournament: ' +
                        (tournament.name || targetTournamentId) +
                        ' (reversed ' + result.eliminationsReversed +
                        ' elimination(s))';
                }
                return 'Removed round ' + roundDisplayNumber +
                    ' from tournament: ' +
                    (tournament.name || targetTournamentId);
            },
            successMessage: 'Round removed successfully!',
            failureMessage: 'Failed to remove round.'
        });
    }

