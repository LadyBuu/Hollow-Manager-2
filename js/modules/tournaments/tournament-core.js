    /**
     * Transition a tournament to a new status.
     *
     * A winner is NOT required for the active→completed transition.
     * Completion requires:
     *   - Lifecycle permits the transition.
     *   - Domain is ready (Rules.isReadyForCompletion).
     *   - Every round's status is 'completed'.
     */
    function transitionStatus(tournamentId, newStatus, force) {
        force = force === true;

        if (!Schema.isValidStatus(newStatus)) {
            return Promise.resolve(
                failure('Invalid status: ' + newStatus)
            );
        }

        var tournament = getValidatedTournament(tournamentId, false);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var currentStatus = tournament.status;

        if (!Lifecycle.isValidStatusTransition(
            currentStatus,
            newStatus
        )) {
            return Promise.resolve(failure(
                'Transition from "' + currentStatus +
                '" to "' + newStatus + '" is not allowed.'
            ));
        }

        if (currentStatus === newStatus) {
            return Promise.resolve(failure(
                'Tournament is already in status "' + newStatus + '".'
            ));
        }

        if (!force) {
            if (currentStatus === 'draft' && newStatus === 'active') {
                if (Rules &&
                    typeof Rules.canStartTournament === 'function') {
                    if (!Rules.canStartTournament(tournament)) {
                        return Promise.resolve(failure(
                            'Tournament prerequisites for start ' +
                            'are not met.'
                        ));
                    }
                }
            }

            if (currentStatus === 'active' &&
                newStatus === 'completed') {
                if (Rules &&
                    typeof Rules.isReadyForCompletion === 'function') {
                    if (!Rules.isReadyForCompletion(tournament)) {
                        return Promise.resolve(failure(
                            'Tournament is not ready for completion.'
                        ));
                    }
                }

                var allRoundsComplete =
                    Array.isArray(tournament.rounds) &&
                    tournament.rounds.length > 0 &&
                    tournament.rounds.every(function(r) {
                        return r && r.status === 'completed';
                    });

                if (!allRoundsComplete) {
                    return Promise.resolve(failure(
                        'All rounds must be complete.'
                    ));
                }
                // No winner requirement.
            }
        }

        var targetId = normaliseId(tournamentId);

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                if (current.status !== currentStatus) {
                    return {
                        valid: false,
                        message:
                            'Tournament status has changed since this ' +
                            'request was made.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                current.status = newStatus;
                return { id: targetId, status: newStatus };
            },
            logMessage: 'Transitioned tournament to "' + newStatus +
                '": ' + (tournament.name || targetId),
            successMessage: 'Tournament status updated!',
            failureMessage: 'Failed to update tournament status.'
        });
    }

    /**
     * Complete a tournament.
     *
     * Thin wrapper around transitionStatus. No winner required.
     */
    function completeTournament(tournamentId, force) {
        return transitionStatus(tournamentId, 'completed', force === true);
    }

