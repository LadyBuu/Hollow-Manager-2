    /**
     * Transition a tournament to a new status.
     *
     * No completion gate. Any status can transition to any other. The
     * user is the authority. Rounds do not need to be complete. No
     * winner is required. Nothing is checked.
     */
    function transitionStatus(tournamentId, newStatus, force) {
        // force is now ignored — kept in signature for compatibility.
        force = force === true;

        if (!Schema.isValidStatus(newStatus)) {
            return Promise.resolve(
                failure('Invalid status: ' + newStatus)
            );
        }

        var tournament = getValidatedTournament(tournamentId, false);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var currentStatus = tournament.status;

        if (currentStatus === newStatus) {
            return Promise.resolve(failure(
                'Tournament is already in status "' + newStatus + '".'
            ));
        }

        var targetId = normaliseId(tournamentId);

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                if (current.status !== currentStatus) {
                    return {
                        valid: false,
                        message:
                            'Tournament status has changed since this ' +
                            'request was made.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                current.status = newStatus;
                return { id: targetId, status: newStatus };
            },
            logMessage: 'Transitioned tournament to "' + newStatus +
                '": ' + (tournament.name || targetId),
            successMessage: 'Tournament status updated!',
            failureMessage: 'Failed to update tournament status.'
        });
    }

    function completeTournament(tournamentId, force) {
        return transitionStatus(tournamentId, 'completed', force === true);
    }

