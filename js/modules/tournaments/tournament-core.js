    function generateUniqueTournamentId(appData) {
        var attempts = 0;
        var maxAttempts = 10;
        var id;
        var generated = false;

        while (!generated && attempts < maxAttempts) {
            id = IdUtils.generateId('tourn');
            attempts++;

            var normalisedId_ = normaliseId(id);
            if (normalisedId_ === null) {
                continue;
            }

            var collision = Array.isArray(appData.tournaments) &&
                appData.tournaments.some(function(t) {
                    return t && normaliseId(t.id) === normalisedId_;
                });

            if (!collision) {
                generated = true;
            }
        }

        if (!generated) {
            return null;
        }
        return normaliseId(id);
    }

