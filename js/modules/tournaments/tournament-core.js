    function addParticipant(tournamentId, participant) {
        if (!isObject(participant)) {
            return Promise.resolve(
                failure('Participant data is required.')
            );
        }

        var id = normaliseId(participant.id);
        if (id === null) {
            return Promise.resolve(
                failure('Participant ID is required.')
            );
        }

        var type = participant.type;
        if (!Schema.isValidParticipantType(type)) {
            return Promise.resolve(failure(
                'Invalid participant type: ' + type
            ));
        }

        var tournament = getTournamentInternal(tournamentId);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var canonicalType = Schema.getCanonicalParticipantType(
            tournament.mode
        );
        if (canonicalType === null || type !== canonicalType) {
            return Promise.resolve(failure(
                'Participant type "' + type +
                '" does not match tournament mode "' +
                tournament.mode + '" (expected "' +
                canonicalType + '").'
            ));
        }

        if (Schema.isParticipantInTournament(tournament, id)) {
            return Promise.resolve(failure(
                'Participant is already in this tournament.'
            ));
        }

        var targetId = normaliseId(tournamentId);

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }

                var currentCanonical = Schema
                    .getCanonicalParticipantType(current.mode);
                if (currentCanonical === null ||
                    type !== currentCanonical) {
                    return {
                        valid: false,
                        message:
                            'Participant type no longer matches ' +
                            'tournament mode.'
                    };
                }

                if (Schema.isParticipantInTournament(current, id)) {
                    return {
                        valid: false,
                        message:
                            'Participant is already in this tournament.'
                    };
                }

                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                if (!Array.isArray(current.participants)) {
                    current.participants = [];
                }
                current.participants.push({
                    id: id,
                    type: type,
                    addedAt: new Date().toISOString()
                });
                return { participantId: id, type: type };
            },
            logMessage: 'Added participant to tournament: ' +
                (tournament.name || targetId),
            successMessage: 'Participant added successfully!',
            failureMessage: 'Failed to add participant.'
        });
    }

    function removeParticipant(tournamentId, participantId) {
        var id = normaliseId(participantId);
        if (id === null) {
            return Promise.resolve(
                failure('Participant ID is required.')
            );
        }

        var tournament = getTournamentInternal(tournamentId);
        if (!tournament || !Array.isArray(tournament.participants)) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var found = false;
        for (var i = 0; i < tournament.participants.length; i++) {
            if (normaliseId(tournament.participants[i].id) === id) {
                found = true;
                break;
            }
        }
        if (!found) {
            return Promise.resolve(failure(
                'Participant not found in this tournament.'
            ));
        }

        var targetId = normaliseId(tournamentId);

        return MutationPipeline.performMutation({
            validate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current) {
                    return {
                        valid: false,
                        message: 'Tournament no longer exists.'
                    };
                }
                var present = Array.isArray(current.participants) &&
                    current.participants.some(function(p) {
                        return p && normaliseId(p.id) === id;
                    });
                if (!present) {
                    return {
                        valid: false,
                        message: 'Participant no longer exists.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appDataSnapshot) {
                var current = findTournamentInSnapshot(
                    appDataSnapshot,
                    targetId
                );
                if (!current || !Array.isArray(current.participants)) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                current.participants = current.participants.filter(
                    function(p) {
                        return !(p && normaliseId(p.id) === id);
                    }
                );
                return { participantId: id };
            },
            logMessage: 'Removed participant from tournament: ' +
                (tournament.name || targetId),
            successMessage: 'Participant removed successfully!',
            failureMessage: 'Failed to remove participant.'
        });
    }

