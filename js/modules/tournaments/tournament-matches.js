    function completeMatch(tournamentId, roundId, matchId, result) {
        if (!isObject(result)) {
            return Promise.resolve(failure('Invalid result.'));
        }
        if (!isNonEmptyString(roundId) || !isNonEmptyString(matchId)) {
            return Promise.resolve(
                failure('Round ID and match ID are required.')
            );
        }

        var tournament = Queries.getTournament(tournamentId);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundById(tournament, roundId);
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        var match = Schema.findMatchById(round, matchId);
        if (!match) {
            return Promise.resolve(failure('Match not found.'));
        }

        if (match.status === 'completed') {
            return Promise.resolve(
                failure('Match is already completed.')
            );
        }

        var eliminationWeek = CalendarValidation.parseWeek(
            tournament.endWeek
        );
        if (eliminationWeek === null) {
            return Promise.resolve(failure(
                'Tournament has no valid endWeek. ' +
                'Cannot determine the elimination week. ' +
                'Set the tournament endWeek and retry.'
            ));
        }

        var type = match.type;
        var updates = { status: 'completed' };

        if (type === 'group_exam') {
            var rawResults = result.results;
            if (!isObject(rawResults) ||
                Object.keys(rawResults).length === 0) {
                return Promise.resolve(
                    failure('Results are required for a group exam.')
                );
            }

            var participants = Array.isArray(match.participants)
                ? match.participants
                : [];
            var check = validateResultMap(
                rawResults,
                participants,
                { requireAll: true }
            );
            if (!check.valid) {
                return Promise.resolve(failure(check.message));
            }
            updates.results = check.map;

            if (match.isPairExam && Array.isArray(match.pairings)) {
                updates.isPairExam = true;
                updates.pairings = deepClone(match.pairings);
            }
        }

        if (type === 'team_vs_team') {
            var rawTeam = result.teamResults;
            var rawInd = result.individualResults || {};

            if (!isObject(rawTeam) ||
                Object.keys(rawTeam).length === 0) {
                return Promise.resolve(
                    failure('teamResults are required for a team match.')
                );
            }

            var teams = Array.isArray(match.participants)
                ? match.participants
                : [];
            var teamCheck = validateResultMap(
                rawTeam,
                teams,
                { requireAll: true }
            );
            if (!teamCheck.valid) {
                return Promise.resolve(failure(teamCheck.message));
            }
            updates.teamResults = teamCheck.map;

            if (isObject(rawInd)) {
                var indCheck = validateResultMap(
                    rawInd,
                    null,
                    { requireAll: false }
                );
                if (!indCheck.valid) {
                    return Promise.resolve(failure(indCheck.message));
                }
                updates.individualResults = indCheck.map;
            }
        }

        var proposed = buildProposedMatch(
            match,
            updates,
            tournament,
            round,
            { allowCompletion: true }
        );

        if (!proposed) {
            return Promise.resolve(
                failure('Failed to build completed match.')
            );
        }

        var validationResult = validateProposedMatch(
            proposed, tournament, round, matchId
        );
        if (!validationResult.valid) {
            return Promise.resolve(
                failure(validationResult.errors.join('; '))
            );
        }

        var completedMatch = deepClone(proposed);
        var targetTournamentId = normaliseId(tournamentId);
        var targetRoundId = normaliseId(roundId);
        var targetMatchId = normaliseId(matchId);

        return executeMutation({
            validate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData, targetTournamentId, targetRoundId
                );
                if (!snapshotRound) {
                    return {
                        valid: false,
                        message: 'Round no longer exists.'
                    };
                }
                var snapshotMatch = Schema.findMatchByIdInternal(
                    snapshotRound,
                    targetMatchId
                );
                if (!snapshotMatch) {
                    return {
                        valid: false,
                        message: 'Match no longer exists.'
                    };
                }
                if (snapshotMatch.status === 'completed') {
                    return {
                        valid: false,
                        message: 'Match is already completed.'
                    };
                }
                return { valid: true };
            },
            mutate: function(appData) {
                var snapshotTournament = findTournamentInSnapshot(
                    appData, targetTournamentId
                );
                if (!snapshotTournament) {
                    throw new Error(
                        'Tournament not found in data store.'
                    );
                }
                var snapshotRound = Schema.findRoundByIdInternal(
                    snapshotTournament, targetRoundId
                );
                if (!snapshotRound ||
                    !Array.isArray(snapshotRound.matches)) {
                    throw new Error(
                        'Round not found in data store.'
                    );
                }

                var idx = Schema.findMatchIndexById(
                    snapshotRound,
                    targetMatchId
                );
                if (idx === -1) {
                    throw new Error(
                        'Match not found in data store.'
                    );
                }

                snapshotRound.matches[idx] = deepClone(completedMatch);

                var cascade = EliminationCascade.applyFailEliminations(
                    appData,
                    snapshotTournament,
                    snapshotRound.matches[idx],
                    snapshotRound,
                    eliminationWeek
                );

                var promoted = reconcileRoundStatus(snapshotRound);

                return {
                    match: snapshotRound.matches[idx],
                    roundReconciled: promoted,
                    eliminationsWritten: cascade.written,
                    eliminationsReplaced: cascade.replaced,
                    eliminatedCharacterIds: cascade.characterIds
                };
            },
            logMessage: function(result) {
                if (result && result.eliminationsWritten > 0) {
                    return 'Completed match (eliminated ' +
                        result.eliminationsWritten +
                        ' participant(s))';
                }
                return 'Completed match';
            },
            successMessage: 'Match completed successfully.',
            failureMessage: 'Failed to complete match.'
        });
    }

