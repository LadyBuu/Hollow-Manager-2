/**
 * modules/tournaments/tournament-matches.js - Tournament Match Operations
 * CANONICAL match mutation API for tournaments.
 *
 * Path: js/modules/tournaments/tournament-matches.js
 *
 * RESPONSIBILITIES:
 *   - Match CRUD (create, update, delete)
 *   - Match completion (per-participant pass/fail/retry)
 *   - Team match completion (team-level + member-level results)
 *   - Auto-generation of matches from an eligible pool
 *   - Internal pure builders for Core.addRound
 *   - Round promotion: when the last match in a round completes, the
 *     round's status is set to 'completed'
 *
 * NOT RESPONSIBILITIES:
 *   - Tournament-level status transitions (TournamentCore)
 *   - Round addition/removal (TournamentCore)
 *   - Persistence (MutationPipeline)
 *   - Rendering, notifications
 *
 * IDENTITY:
 *   Rounds and matches carry stable IDs generated by TournamentSchema.
 *   All public commands accept IDs, not array indices. Lookup goes
 *   through Schema.findRoundById / Schema.findMatchById.
 *
 * ROUND STATUS PROMOTION:
 *   Completing a match does not automatically complete the tournament.
 *   It does automatically promote the round to 'completed' when every
 *   match in the round is completed. This is required by
 *   TournamentRules.validateCompletionReadiness, which requires each
 *   round's status to be 'completed' before the tournament can be
 *   marked complete. Without this promotion, no tournament could ever
 *   be completed.
 *
 * MATCH TYPES:
 *   'standard'    : legacy 2-participant match. Read-only compat.
 *   'group_exam'  : open assessment. 2+ participants. Per-participant
 *                   results (pass | fail | retry).
 *   'team_vs_team': adversarial team match. 2+ teams. Two-layer
 *                   results: teamResults + individualResults.
 *
 * PAIR EXAM:
 *   'group_exam' with isPairExam: true. Pairings partition participants
 *   into groups of 2 or 3.
 *
 * RESULT VOCABULARY:
 *   'pass' | 'retry' | 'fail'. Advancement = 'pass' or 'retry'.
 *
 * DEPENDENCIES (MANDATORY):
 *   - window.TournamentConstants
 *   - window.TournamentSchema
 *   - window.TournamentLifecycle
 *   - window.TournamentRules
 *   - window.TournamentQueries
 *   - window.MutationPipeline
 *   - window.ObjectUtils
 *   - window.IdUtils
 *
 * USAGE:
 *   var Matches = window.TournamentMatches;
 *
 *   Matches.createMatch('tourn_123', 'round_abc', {
 *       participants: ['char_1', 'char_2']
 *   });
 *
 *   Matches.completeMatch('tourn_123', 'round_abc', 'match_xyz', {
 *       results: { char_1: 'pass', char_2: 'retry' }
 *   });
 *
 *   Matches.generateMatches('tourn_123', 'round_abc', { matchSize: 2 });
 */

