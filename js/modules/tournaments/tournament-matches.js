    function applyMatchUpdate(target, updated) {
        var keys = [
            'participants',
            'type',
            'status',
            'winner',
            'loser',
            'advancing',
            'results',
            'isPairExam',
            'pairings',
            'teamResults',
            'individualResults'
        ];
        for (var i = 0; i < keys.length; i++) {
            var key = keys[i];
            if (updated[key] !== undefined) {
                target[key] = updated[key];
            } else {
                delete target[key];
            }
        }
    }

