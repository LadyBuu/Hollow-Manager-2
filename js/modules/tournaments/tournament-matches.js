    function executeMutation(config) {
        return MutationPipeline.performMutation({
            validate: config.validate || function() {
                return { valid: true };
            },
            mutate: config.mutate,
            logMessage: config.logMessage || 'Match operation performed.',
            successMessage: config.successMessage ||
                'Match operation completed.',
            failureMessage: config.failureMessage ||
                'Match operation failed.'
        });
    }

    // ============================================================
    // PUBLIC COMMAND - Create Match
    // ============================================================

    function createMatch(tournamentId, roundId, matchData) {
        if (!isObject(matchData)) {
            return Promise.resolve(failure('Invalid match data.'));
        }
        if (!isNonEmptyString(roundId)) {
            return Promise.resolve(failure('Round ID is required.'));
        }

        var tournament = Queries.getTournament(tournamentId);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundById(tournament, roundId);
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        if (round.status === 'completed') {
            return Promise.resolve(
                failure('Cannot add matches to a completed round.')
            );
        }

        var participants = matchData.participants || [];
        var validation = validateMatchParticipants(
            tournamentId,
            participants
        );
        if (!validation.valid) {
            return Promise.resolve(failure(validation.message));
        }

        var base = buildMatch([], {
            matchType: matchData.type || round.matchType || 'group_exam',
            isPairExam: matchData.isPairExam === true ||
                round.isPairExam === true
        });

        var updates = {
            participants: participants,
            type: matchData.type || round.matchType || 'group_exam'
        };

        if (matchData.isPairExam === true || round.isPairExam === true) {
            updates.isPairExam = true;
            if (Array.isArray(matchData.pairings)) {
                updates.pairings = matchData.pairings;
            }
        }

        var proposed = buildProposedMatch(base, updates, tournament, round);
        if (!proposed) {
            return Promise.resolve(failure('Failed to build match.'));
        }

        var validationResult = validateProposedMatch(
            proposed, tournament, round, null
        );
        if (!validationResult.valid) {
            return Promise.resolve(
                failure(validationResult.errors.join('; '))
            );
        }

        if (proposed.isPairExam &&
            (!proposed.pairings || proposed.pairings.length === 0)) {
            var autoPairings = partitionIntoPairs(proposed.participants);
            if (autoPairings) {
                proposed.pairings = autoPairings;
            }
        }

        var matchCopy = deepClone(proposed);
        var targetTournamentId = normaliseId(tournamentId);
        var targetRoundId = normaliseId(roundId);

        return executeMutation({
            validate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData, targetTournamentId, targetRoundId
                );
                if (!snapshotRound) {
                    return { valid: false, message: 'Round no longer exists.' };
                }
                if (snapshotRound.status === 'completed') {
                    return { valid: false, message: 'Round is completed.' };
                }
                return { valid: true };
            },
            mutate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData, targetTournamentId, targetRoundId
                );
                if (!snapshotRound) {
                    throw new Error('Round not found in data store.');
                }
                if (!Array.isArray(snapshotRound.matches)) {
                    snapshotRound.matches = [];
                }
                snapshotRound.matches.push(matchCopy);
                return { match: matchCopy };
            },
            logMessage: 'Added match to round',
            successMessage: 'Match added successfully.',
            failureMessage: 'Failed to add match.'
        });
    }

    // ============================================================
    // PUBLIC COMMAND - Remove Match
    // ============================================================
    //
    // ELIMINATION REVERSAL:
    //   If the removed match was completed, its eliminations are
    //   reversed BEFORE the match is spliced out. Reversal touches
    //   both tournament.eliminations[] and character.eliminations[],
    //   keyed by (tournamentId, fromMatchId). Standalone eliminations
    //   and legacy eliminations without provenance are not touched.
    //
    //   The reversal runs inside the same transaction as the removal.
    //   If persistence fails, both the removal and the reversal roll
    //   back together.

    function removeMatch(tournamentId, roundId, matchId) {
        if (!isNonEmptyString(roundId) || !isNonEmptyString(matchId)) {
            return Promise.resolve(
                failure('Round ID and match ID are required.')
            );
        }

        var tournament = Queries.getTournament(tournamentId);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundById(tournament, roundId);
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        var match = Schema.findMatchById(round, matchId);
        if (!match) {
            return Promise.resolve(failure('Match not found.'));
        }

        var targetTournamentId = normaliseId(tournamentId);
        var targetRoundId = normaliseId(roundId);
        var targetMatchId = normaliseId(matchId);
        var matchWasCompleted = match.status === 'completed';

        return executeMutation({
            validate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData, targetTournamentId, targetRoundId
                );
                if (!snapshotRound) {
                    return { valid: false, message: 'Round no longer exists.' };
                }
                if (!Schema.findMatchById(snapshotRound, targetMatchId)) {
                    return { valid: false, message: 'Match no longer exists.' };
                }
                return { valid: true };
            },
            mutate: function(appData) {
                var snapshotTournament = findTournamentInSnapshot(
                    appData, targetTournamentId
                );
                if (!snapshotTournament) {
                    throw new Error('Tournament not found in data store.');
                }
                var snapshotRound = Schema.findRoundById(
                    snapshotTournament, targetRoundId
                );
                if (!snapshotRound || !Array.isArray(snapshotRound.matches)) {
                    throw new Error('Round not found in data store.');
                }

                var idx = -1;
                for (var i = 0; i < snapshotRound.matches.length; i++) {
                    if (normaliseId(snapshotRound.matches[i].id) === targetMatchId) {
                        idx = i;
                        break;
                    }
                }
                if (idx === -1) {
                    throw new Error('Match not found in data store.');
                }

                // ---- Reverse eliminations BEFORE splicing the match ----
                // We check the LIVE match status in the snapshot, not
                // the pre-flight status, because another mutation may
                // have completed the match between pre-flight and now.
                var liveMatch = snapshotRound.matches[idx];
                var reversal = { reversed: 0, characterIds: [] };
                if (liveMatch && liveMatch.status === 'completed') {
                    reversal = EliminationCascade.reverseMatchEliminations(
                        appData,
                        snapshotTournament,
                        targetMatchId
                    );
                }

                snapshotRound.matches.splice(idx, 1);

                return {
                    removed: true,
                    eliminationsReversed: reversal.reversed,
                    reversedCharacterIds: reversal.characterIds
                };
            },
            logMessage: function(result) {
                if (result && result.eliminationsReversed > 0) {
                    return 'Removed match (reversed ' +
                        result.eliminationsReversed +
                        ' elimination(s))';
                }
                return 'Removed match from round';
            },
            successMessage: 'Match removed successfully.',
            failureMessage: 'Failed to remove match.'
        });
    }

