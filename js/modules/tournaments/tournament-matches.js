    function findTournamentInSnapshot(appData, tournamentId) {
        if (!appData || !Array.isArray(appData.tournaments)) {
            return null;
        }
        var target = normaliseId(tournamentId);
        if (target === null) { return null; }
        for (var i = 0; i < appData.tournaments.length; i++) {
            var t = appData.tournaments[i];
            if (t && normaliseId(t.id) === target) {
                return t;
            }
        }
        return null;
    }

    function findRoundInSnapshot(appData, tournamentId, roundId) {
        var tournament = findTournamentInSnapshot(appData, tournamentId);
        if (!tournament) { return null; }
        return Schema.findRoundById(tournament, roundId);
    }

    function findMatchInSnapshot(appData, tournamentId, roundId, matchId) {
        var round = findRoundInSnapshot(appData, tournamentId, roundId);
        if (!round) { return null; }
        return Schema.findMatchById(round, matchId);
    }

    // ============================================================
    // ELIGIBILITY
    // ============================================================
    //
    // A participant is eligible for a NEW match in a round when:
    //   - They are in the tournament roster.
    //   - They have not been individually eliminated.
    //   - They have not failed any prior completed match in this
    //     tournament.
    //
    // Reads via TournamentQueries. This is a pre-flight helper used by
    // generateMatches and the pool preview; it is not part of the
    // mutation critical path.

    function isEligibleForNewMatch(tournamentId, participantId) {
        if (!participantId) { return false; }

        if (!Queries.isParticipantInTournament(tournamentId, participantId)) {
            return false;
        }

        if (Queries.isParticipantEliminated(tournamentId, participantId)) {
            return false;
        }

        var rounds = Queries.getRounds(tournamentId);
        for (var r = 0; r < rounds.length; r++) {
            var matches = rounds[r] && Array.isArray(rounds[r].matches)
                ? rounds[r].matches
                : [];
            for (var m = 0; m < matches.length; m++) {
                var match = matches[m];
                if (!match || match.status !== 'completed') { continue; }

                if (match.type === 'team_vs_team') {
                    var tr = match.teamResults || {};
                    if (tr[participantId] === 'fail') {
                        return false;
                    }
                } else {
                    var rr = match.results || {};
                    if (rr[participantId] === 'fail') {
                        return false;
                    }
                }
            }
        }

        return true;
    }

    function getEligibleParticipants(tournamentId) {
        var tournament = Queries.getTournament(tournamentId);
        if (!tournament || !Array.isArray(tournament.participants)) {
            return [];
        }
        var result = [];
        for (var i = 0; i < tournament.participants.length; i++) {
            var p = tournament.participants[i];
            if (!p || !p.id) { continue; }
            if (isEligibleForNewMatch(tournamentId, p.id)) {
                result.push(p.id);
            }
        }
        return result;
    }

    // ============================================================
    // VALIDATION - Match participants
    // ============================================================

    function validateMatchParticipants(tournamentId, participantIds) {
        if (!Array.isArray(participantIds) || participantIds.length < 2) {
            return { valid: false, message: 'At least 2 participants required.' };
        }

        var seen = {};
        var tournament = Queries.getTournament(tournamentId);
        if (!tournament) {
            return { valid: false, message: 'Tournament not found.' };
        }

        var expectedType = getCanonicalParticipantType(tournament.mode);

        for (var i = 0; i < participantIds.length; i++) {
            var id = normaliseId(participantIds[i]);
            if (id === null) {
                return {
                    valid: false,
                    message: 'Invalid participant ID: ' + participantIds[i]
                };
            }
            if (seen[id]) {
                return { valid: false, message: 'Duplicate participant: ' + id };
            }
            seen[id] = true;

            if (!Queries.isParticipantInTournament(tournamentId, id)) {
                return {
                    valid: false,
                    message: 'Participant not in tournament: ' + id
                };
            }

            if (Queries.isParticipantEliminated(tournamentId, id)) {
                return {
                    valid: false,
                    message: 'Participant is eliminated: ' + id
                };
            }

            var actualType = Queries.getParticipantTypeFromRecord(
                tournamentId,
                id
            );
            if (actualType && actualType !== expectedType) {
                return {
                    valid: false,
                    message: 'Participant type mismatch for ' + id +
                        '. Expected ' + expectedType + ', got ' + actualType
                };
            }
        }

        return { valid: true };
    }

    // ============================================================
    // VALIDATION - Result maps
    // ============================================================

    function validateResultMap(rawMap, participants, options) {
        options = options || {};
        var requireAll = options.requireAll === true;

        if (!isObject(rawMap)) {
            return { valid: false, message: 'Results must be an object.' };
        }

        var normalised = {};
        var keys = Object.keys(rawMap);
        for (var i = 0; i < keys.length; i++) {
            var key = keys[i];
            var id = normaliseId(key);
            if (id === null) {
                return { valid: false, message: 'Invalid result key: ' + key };
            }
            if (Array.isArray(participants) &&
                participants.indexOf(id) === -1) {
                return {
                    valid: false,
                    message: 'Result for ' + id +
                        ' does not match a match participant.'
                };
            }
            var value = rawMap[key];
            if (!isValidResult(value)) {
                return {
                    valid: false,
                    message: 'Invalid result for ' + id + ': ' + value +
                        ' (expected pass, fail, or retry)'
                };
            }
            normalised[id] = value;
        }

        if (requireAll && Array.isArray(participants)) {
            for (var j = 0; j < participants.length; j++) {
                var pid = normaliseId(participants[j]);
                if (pid !== null && normalised[pid] === undefined) {
                    return {
                        valid: false,
                        message: 'Missing result for participant: ' + pid
                    };
                }
            }
        }

        return { valid: true, map: normalised };
    }

