    function isEligibleForNewMatch(tournamentId, participantId) {
        if (!participantId) { return false; }

        if (!Queries.isParticipantInTournament(
            tournamentId,
            participantId
        )) {
            return false;
        }

        if (Queries.isParticipantEliminated(
            tournamentId,
            participantId
        )) {
            return false;
        }

        var tournament = Queries.getTournament(tournamentId);
        if (!tournament || !Array.isArray(tournament.rounds)) {
            return true;
        }

        for (var r = 0; r < tournament.rounds.length; r++) {
            var round = tournament.rounds[r];
            if (!round || !Array.isArray(round.matches)) { continue; }
            for (var m = 0; m < round.matches.length; m++) {
                var match = round.matches[m];
                if (!match || match.status !== 'completed') { continue; }

                if (match.type === 'team_vs_team') {
                    var tr = match.teamResults || {};
                    if (tr[participantId] === 'fail') {
                        return false;
                    }
                } else {
                    var rr = match.results || {};
                    if (rr[participantId] === 'fail') {
                        return false;
                    }
                }
            }
        }

        return true;
    }

    function getEligibleParticipants(tournamentId) {
        var tournament = Queries.getTournament(tournamentId);
        if (!tournament || !Array.isArray(tournament.participants)) {
            return [];
        }
        var result = [];
        for (var i = 0; i < tournament.participants.length; i++) {
            var p = tournament.participants[i];
            if (!p || !p.id) { continue; }
            if (isEligibleForNewMatch(tournamentId, p.id)) {
                result.push(p.id);
            }
        }
        return result;
    }

    // ============================================================
    // MATCH PARTICIPANT VALIDATION - PREFLIGHT (query-based)
    // ============================================================

    function validateMatchParticipantsPreflight(
        tournamentId,
        participantIds
    ) {
        if (!Array.isArray(participantIds) || participantIds.length < 2) {
            return {
                valid: false,
                message: 'At least 2 participants required.'
            };
        }

        var seen = Object.create(null);
        var tournament = Queries.getTournament(tournamentId);
        if (!tournament) {
            return { valid: false, message: 'Tournament not found.' };
        }

        var expectedType = Schema.getCanonicalParticipantType(
            tournament.mode
        );

        for (var i = 0; i < participantIds.length; i++) {
            var id = normaliseId(participantIds[i]);
            if (id === null) {
                return {
                    valid: false,
                    message:
                        'Invalid participant ID: ' + participantIds[i]
                };
            }
            if (seen[id]) {
                return {
                    valid: false,
                    message: 'Duplicate participant: ' + id
                };
            }
            seen[id] = true;

            if (!Queries.isParticipantInTournament(tournamentId, id)) {
                return {
                    valid: false,
                    message: 'Participant not in tournament: ' + id
                };
            }

            if (Queries.isParticipantEliminated(tournamentId, id)) {
                return {
                    valid: false,
                    message: 'Participant is eliminated: ' + id
                };
            }

            var actualType = Queries.getParticipantTypeFromRecord(
                tournamentId,
                id
            );
            if (actualType && actualType !== expectedType) {
                return {
                    valid: false,
                    message: 'Participant type mismatch for ' + id +
                        '. Expected ' + expectedType + ', got ' + actualType
                };
            }
        }

        return { valid: true };
    }

    // ============================================================
    // MATCH PARTICIPANT VALIDATION - SNAPSHOT (authoritative)
    // ============================================================

    function validateMatchParticipantsInSnapshot(
        appData,
        tournamentId,
        participantIds
    ) {
        if (!Array.isArray(participantIds) || participantIds.length < 2) {
            return {
                valid: false,
                message: 'At least 2 participants required.'
            };
        }

        var tournament = findTournamentInSnapshot(appData, tournamentId);
        if (!tournament) {
            return { valid: false, message: 'Tournament no longer exists.' };
        }

        var expectedType = Schema.getCanonicalParticipantType(
            tournament.mode
        );

        var participantIds_set = Object.create(null);
        for (var p = 0; p < tournament.participants.length; p++) {
            var tp = tournament.participants[p];
            if (tp && isNonEmptyString(tp.id)) {
                participantIds_set[String(tp.id)] = true;
            }
        }

        var seen = Object.create(null);

        for (var i = 0; i < participantIds.length; i++) {
            var id = normaliseId(participantIds[i]);
            if (id === null) { return { valid: false, message: 'Invalid participant ID.' }; }
            if (seen[id]) { return { valid: false, message: 'Duplicate participant.' }; }
            seen[id] = true;

            if (!participantIds_set[id]) {
                return {
                    valid: false,
                    message: 'Participant ' + id +
                        ' is no longer in the tournament.'
                };
            }

            if (Schema.isParticipantEliminated(tournament, id)) {
                return {
                    valid: false,
                    message: 'Participant ' + id +
                        ' has been eliminated.'
                };
            }

            var actualType = Schema.getParticipantTypeFromRecord(
                tournament,
                id
            );
            if (actualType !== expectedType) {
                return {
                    valid: false,
                    message: 'Participant type mismatch for ' + id + '.'
                };
            }
        }

        return { valid: true };
    }

    // ============================================================
    // RESULT-MAP VALIDATION
    // ============================================================

    function validateResultMap(rawMap, participants, options) {
        options = options || {};
        var requireAll = options.requireAll === true;

        if (!isObject(rawMap)) {
            return { valid: false, message: 'Results must be an object.' };
        }

        var normalised = {};
        var keys = Object.keys(rawMap);
        for (var i = 0; i < keys.length; i++) {
            var key = keys[i];
            var id = normaliseId(key);
            if (id === null) {
                return {
                    valid: false,
                    message: 'Invalid result key: ' + key
                };
            }
            if (Array.isArray(participants) &&
                participants.indexOf(id) === -1) {
                return {
                    valid: false,
                    message: 'Result for ' + id +
                        ' does not match a match participant.'
                };
            }
            var value = rawMap[key];
            if (!isValidResult(value)) {
                return {
                    valid: false,
                    message: 'Invalid result for ' + id + ': ' + value +
                        ' (expected pass, fail, or retry)'
                };
            }
            normalised[id] = value;
        }

        if (requireAll && Array.isArray(participants)) {
            for (var j = 0; j < participants.length; j++) {
                var pid = normaliseId(participants[j]);
                if (pid !== null && normalised[pid] === undefined) {
                    return {
                        valid: false,
                        message: 'Missing result for participant: ' + pid
                    };
                }
            }
        }

        return { valid: true, map: normalised };
    }

