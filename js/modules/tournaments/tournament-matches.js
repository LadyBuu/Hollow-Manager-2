    function hasOnlyAllowedKeys(object, allowedKeys) {
        var keys = Object.keys(object);
        for (var i = 0; i < keys.length; i++) {
            if (allowedKeys.indexOf(keys[i]) === -1) {
                return false;
            }
        }
        return true;
    }

    function isTypeChangeAllowed(base) {
        if (!base) { return false; }
        if (base.status !== 'pending') { return false; }
        if (base.results && Object.keys(base.results).length > 0) {
            return false;
        }
        if (base.teamResults && Object.keys(base.teamResults).length > 0) {
            return false;
        }
        if (base.individualResults &&
            Object.keys(base.individualResults).length > 0) {
            return false;
        }
        if (base.winner) { return false; }
        return true;
    }

    function normaliseIdArrayStrict(ids) {
        if (!Array.isArray(ids)) { return null; }
        var result = [];
        var seen = {};
        for (var i = 0; i < ids.length; i++) {
            var normalised = normaliseId(ids[i]);
            if (normalised === null) { return null; }
            if (seen[normalised]) { return null; }
            seen[normalised] = true;
            result.push(normalised);
        }
        return result;
    }

    function validateMatchResultParticipants(participants, results) {
        if (!results || typeof results !== 'object') {
            return true;
        }
        var participantIds = participants.map(normaliseId).filter(function(id) {
            return id !== null;
        });
        var keys = Object.keys(results);
        for (var i = 0; i < keys.length; i++) {
            var id = normaliseId(keys[i]);
            if (id === null) { return false; }
            if (participantIds.indexOf(id) === -1) { return false; }
        }
        return true;
    }

    // ============================================================
    // ROUND PROMOTION
    // ============================================================

    function promoteRoundIfComplete(round) {
        if (!round || !Array.isArray(round.matches)) { return false; }
        if (round.matches.length === 0) { return false; }
        if (round.status === 'completed') { return false; }

        for (var i = 0; i < round.matches.length; i++) {
            var m = round.matches[i];
            if (!m || m.status !== 'completed') {
                return false;
            }
        }

        round.status = 'completed';
        return true;
    }

