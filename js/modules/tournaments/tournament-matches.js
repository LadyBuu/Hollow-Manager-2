    function generateMatches(tournamentId, roundId, options) {
        options = options || {};

        if (!isNonEmptyString(roundId)) {
            return Promise.resolve(failure('Round ID is required.'));
        }

        var tournament = Queries.getTournament(tournamentId);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundById(tournament, roundId);
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        if (round.status === 'completed') {
            return Promise.resolve(
                failure('Cannot add matches to a completed round.')
            );
        }

        // ---- determine match size ----
        var matchSize = parseInt(options.matchSize, 10);
        if (isNaN(matchSize) || matchSize < 2) {
            matchSize = round.matchSize || 2;
        }

        var isPairExam = round.isPairExam === true ||
            options.isPairExam === true;
        if (isPairExam) {
            matchSize = 2;
        }

        // ---- eligible pool ----
        var pool = getEligibleParticipants(tournamentId);

        // Exclude anyone already placed in a match within this round.
        var alreadyInRound = {};
        if (Array.isArray(round.matches)) {
            for (var m = 0; m < round.matches.length; m++) {
                var existing = round.matches[m];
                if (existing && Array.isArray(existing.participants)) {
                    for (var p = 0; p < existing.participants.length; p++) {
                        var pid = normaliseId(existing.participants[p]);
                        if (pid !== null) {
                            alreadyInRound[pid] = true;
                        }
                    }
                }
            }
        }

        var eligible = pool.filter(function(id) {
            return !alreadyInRound[id];
        });

        if (eligible.length < 2) {
            return Promise.resolve(failure(
                'Not enough eligible participants to generate a match ' +
                '(need at least 2, have ' + eligible.length + ').'
            ));
        }

        // ---- partition ----
        var partitions;
        if (isPairExam) {
            partitions = partitionIntoPairs(eligible);
        } else {
            partitions = partitionIntoGroups(eligible, matchSize);
        }

        if (!partitions || partitions.length === 0) {
            return Promise.resolve(
                failure('Could not partition participants.')
            );
        }

        // ---- build proposed matches ----
        var proposedMatches = [];
        var matchType = round.matchType || 'group_exam';
        if (isPairExam && matchType !== 'group_exam') {
            matchType = 'group_exam';
        }

        for (var i = 0; i < partitions.length; i++) {
            var group = partitions[i];
            var base = buildMatch([], {
                matchType: matchType,
                isPairExam: isPairExam
            });
            var updates = {
                participants: group,
                type: matchType
            };
            if (isPairExam) {
                updates.isPairExam = true;
                updates.pairings = [group.slice()];
            }
            var proposed = buildProposedMatch(
                base,
                updates,
                tournament,
                round
            );
            if (!proposed) {
                return Promise.resolve(failure(
                    'Failed to build match for group ' + (i + 1) + '.'
                ));
            }
            proposedMatches.push(proposed);
        }

        var targetTournamentId = normaliseId(tournamentId);
        var targetRoundId = normaliseId(roundId);

        return executeMutation({
            validate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData,
                    targetTournamentId,
                    targetRoundId
                );
                if (!snapshotRound) {
                    return { valid: false, message: 'Round no longer exists.' };
                }
                if (snapshotRound.status === 'completed') {
                    return { valid: false, message: 'Round is completed.' };
                }
                return { valid: true };
            },
            mutate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData,
                    targetTournamentId,
                    targetRoundId
                );
                if (!snapshotRound) {
                    throw new Error('Round not found in data store.');
                }
                if (!Array.isArray(snapshotRound.matches)) {
                    snapshotRound.matches = [];
                }
                var created = [];
                for (var k = 0; k < proposedMatches.length; k++) {
                    var copy = deepClone(proposedMatches[k]);
                    snapshotRound.matches.push(copy);
                    created.push(copy);
                }
                return {
                    createdCount: created.length,
                    matches: created
                };
            },
            logMessage: 'Generated ' + proposedMatches.length + ' match(es)',
            successMessage: 'Matches generated successfully.',
            failureMessage: 'Failed to generate matches.'
        });
    }

    // ============================================================
    // PARTITION HELPERS
    // ============================================================

    function partitionIntoGroups(ids, groupSize) {
        if (!Array.isArray(ids) || ids.length < 2) { return []; }
        if (groupSize < 2) { groupSize = 2; }

        var pool = ids.slice();
        for (var s = pool.length - 1; s > 0; s--) {
            var r = Math.floor(Math.random() * (s + 1));
            var tmp = pool[s];
            pool[s] = pool[r];
            pool[r] = tmp;
        }

        var groups = [];
        for (var i = 0; i < pool.length; i += groupSize) {
            var slice = pool.slice(i, i + groupSize);
            if (slice.length >= 2) {
                groups.push(slice);
            }
        }

        return groups;
    }

    function partitionIntoPairs(ids) {
        if (!Array.isArray(ids) || ids.length < 2) { return []; }

        var pool = ids.slice();
        for (var s = pool.length - 1; s > 0; s--) {
            var r = Math.floor(Math.random() * (s + 1));
            var tmp = pool[s];
            pool[s] = pool[r];
            pool[r] = tmp;
        }

        var groups = [];
        var i = 0;

        if (pool.length % 2 === 1 && pool.length >= 3) {
            groups.push(pool.slice(0, 3));
            i = 3;
        }

        for (; i < pool.length; i += 2) {
            var slice = pool.slice(i, i + 2);
            if (slice.length === 2) {
                groups.push(slice);
            } else if (slice.length === 1) {
                if (groups.length > 0) {
                    groups[groups.length - 1].push(slice[0]);
                }
            }
        }

        return groups;
    }

