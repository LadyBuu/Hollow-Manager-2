    function createMatch(tournamentId, roundId, matchData) {
        if (!isObject(matchData)) {
            return Promise.resolve(failure('Invalid match data.'));
        }
        if (!isNonEmptyString(roundId)) {
            return Promise.resolve(failure('Round ID is required.'));
        }

        var tournament = Queries.getTournament(tournamentId);
        if (!tournament) {
            return Promise.resolve(failure('Tournament not found.'));
        }

        var round = Schema.findRoundById(tournament, roundId);
        if (!round) {
            return Promise.resolve(failure('Round not found.'));
        }

        if (round.status === 'completed') {
            return Promise.resolve(
                failure('Cannot add matches to a completed round.')
            );
        }

        var participants = matchData.participants || [];
        var validation = validateMatchParticipantsPreflight(
            tournamentId,
            participants
        );
        if (!validation.valid) {
            return Promise.resolve(failure(validation.message));
        }

        var base = buildMatch([], {
            matchType: matchData.type || round.matchType || 'group_exam',
            isPairExam: matchData.isPairExam === true ||
                round.isPairExam === true
        });

        var updates = {
            participants: participants,
            type: matchData.type || round.matchType || 'group_exam'
        };

        if (matchData.isPairExam === true || round.isPairExam === true) {
            updates.isPairExam = true;
            if (Array.isArray(matchData.pairings)) {
                updates.pairings = matchData.pairings;
            }
        }

        var proposed = buildProposedMatch(base, updates, tournament, round);
        if (!proposed) {
            return Promise.resolve(failure('Failed to build match.'));
        }

        var validationResult = validateProposedMatch(
            proposed, tournament, round, null
        );
        if (!validationResult.valid) {
            return Promise.resolve(
                failure(validationResult.errors.join('; '))
            );
        }

        if (proposed.isPairExam &&
            (!proposed.pairings || proposed.pairings.length === 0)) {
            var autoPairings = partitionIntoPairs(proposed.participants);
            if (autoPairings) {
                proposed.pairings = autoPairings;
            }
        }

        var matchCopy = deepClone(proposed);
        var targetTournamentId = normaliseId(tournamentId);
        var targetRoundId = normaliseId(roundId);

        return executeMutation({
            validate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData, targetTournamentId, targetRoundId
                );
                if (!snapshotRound) {
                    return {
                        valid: false,
                        message: 'Round no longer exists.'
                    };
                }
                if (snapshotRound.status === 'completed') {
                    return {
                        valid: false,
                        message: 'Round is completed.'
                    };
                }
                var participantCheck = validateMatchParticipantsInSnapshot(
                    appData,
                    targetTournamentId,
                    matchCopy.participants
                );
                if (!participantCheck.valid) {
                    return {
                        valid: false,
                        message: participantCheck.message
                    };
                }
                return { valid: true };
            },
            mutate: function(appData) {
                var snapshotRound = findRoundInSnapshot(
                    appData, targetTournamentId, targetRoundId
                );
                if (!snapshotRound) {
                    throw new Error(
                        'Round not found in data store.'
                    );
                }
                if (!Array.isArray(snapshotRound.matches)) {
                    snapshotRound.matches = [];
                }
                snapshotRound.matches.push(matchCopy);
                reconcileRoundStatus(snapshotRound);
                return { match: matchCopy };
            },
            logMessage: 'Added match to round',
            successMessage: 'Match added successfully.',
            failureMessage: 'Failed to add match.'
        });
    }

