/**
 * js/modules/missions/mission-core.js - Mission Core
 *
 * Path: js/modules/missions/mission-core.js
 *
 * Canonical mutation API for missions.
 *
 * WHAT THIS MODULE OWNS:
 *   - Mission creation, update, archive, unarchive, purge.
 *   - Status transitions: complete, cancel, reactivate.
 *   - Objective mutations: add, remove, toggle.
 *   - Support personnel mutations: add, remove.
 *   - Participant mutations: add, remove.
 *   - Report mutations: add, update, remove.
 *   - MutationPipeline orchestration for all of the above.
 *   - Cascade helper (stripCharacterRefs) for cross-domain cleanup.
 *
 * WHAT THIS MODULE DOES NOT OWN:
 *   - Reads. MissionQueries owns them.
 *   - Structural validation. MissionSchema owns that.
 *   - Domain rules. MissionRules owns them.
 *   - The global audit trail. ActivityLog owns it, and it is
 *     fed by MutationPipeline's logMessage hook, not by this
 *     module.
 *
 * MUTATION PATTERN:
 *   Every mutation follows the same shape:
 *
 *     1. Cheap preflight on the operation's inputs (title present,
 *        updates is an object, etc). Fast UX-level rejection.
 *
 *     2. MutationPipeline.performMutation with:
 *
 *        validate(appData):
 *          - Re-read the mission from the SNAPSHOT, not from a
 *            preflight read.
 *          - Build the candidate by applying the requested changes
 *            to that snapshot mission.
 *          - Recompute derived fields from the candidate's own
 *            objectives and pay inputs.
 *          - Run MissionSchema.validateMission on the candidate
 *            (structural, whole-record).
 *          - Run the operation's MissionRules checks against the
 *            snapshot mission and the candidate.
 *          - Return { valid, message? }.
 *
 *        mutate(appData):
 *          - Locate the mission again in the snapshot (or append for
 *            create).
 *          - Write the validated candidate.
 *          - Return a summary for the log.
 *
 *   Nothing is computed once from a preflight read and then
 *   blind-written. Every invariant is checked against the
 *   transaction snapshot. This is what makes the mutations actually
 *   atomic.
 *
 * SUB-MUTATIONS DO NOT RE-VALIDATE THE WHOLE MISSION:
 *   Report, objective, support-personnel, and participant
 *   mutations touch a narrow slice of a mission that is already in
 *   the store. They do NOT run MissionSchema.validateMission on the
 *   whole record.
 *
 *   They validate:
 *     - that the mission exists in the snapshot;
 *     - that the specific nested record they are about to add,
 *       update, or remove is well-formed (via the appropriate
 *       MissionSchema nested validator);
 *     - the domain rules that belong to the operation itself.
 *
 *   createMission and updateMission are the two operations that DO
 *   run validateMission, because they are the operations through
 *   which a caller supplies structural fields. If those fields are
 *   wrong, the write must be rejected.
 *
 * CREATE MISSION ID:
 *   createMission accepts an OPTIONAL `data.id` parameter. When
 *   supplied and valid, the created mission uses that id instead
 *   of a freshly generated one. When absent, the id is generated
 *   via IdUtils with the 'miss' prefix.
 *
 *   The supplied id must be a valid UUID per IdUtils.normaliseId.
 *   The pipeline's validate step checks for a collision with any
 *   existing mission id and rejects the create if one is found.
 *   Sequence and createdAt are still generated by createMission,
 *   regardless of the id source.
 *
 * ARCHIVE VS PURGE:
 *   Missions follow the historical-preservation model.
 *
 *     archiveMission(id)
 *       Sets archivedAt and status 'completed'. History preserved.
 *       Archived missions are hidden from default queries but stay
 *       queryable. This is the ordinary UI delete.
 *
 *     unarchiveMission(id)
 *       Clears archivedAt. Status is left as-is. The caller decides
 *       whether to also update status.
 *
 *     purgeMission(id)
 *       Permanently removes the mission. Administrative, not wired
 *       to any ordinary UI button.
 *
 * PARTICIPANTS:
 *   A mission carries a `participants` array. Each entry is
 *   { characterId, teamId, source }, where source is 'team' for a
 *   member of one of the mission's assigned teams, or 'rookie' for
 *   a character selected from the rookie candidate list (teamId
 *   null in that case).
 *
 *   addParticipant(missionId, characterId, teamId):
 *     - Resolves the source via MissionRules.resolveParticipantSource.
 *     - Rejects if the (characterId, teamId) pair is already
 *       present.
 *     - Appends the new entry.
 *
 *   removeParticipant(missionId, characterId, teamId):
 *     - Rejects if no matching entry exists.
 *     - Removes the entry.
 *
 *   Both are sub-mutations. They validate the specific participant
 *   record via MissionSchema.validateParticipant, they do not
 *   re-validate the whole mission. They run against the transaction
 *   snapshot so the pair-uniqueness check is race-free.
 *
 *   The pipeline does NOT check that the character exists, that the
 *   team exists, or that the character was a member of the team.
 *   Those are cross-domain concerns. A caller that needs those
 *   guarantees enforces them at the UI layer before calling here.
 *   The mission domain trusts the caller to supply well-formed ids.
 *
 * ORPHANED PARTICIPANTS ON TEAM REMOVAL:
 *   When updateMission is called with a new assignedTeamIds array
 *   that OMITS a team that was previously assigned, any participant
 *   whose teamId points at that removed team is pruned from the
 *   candidate in the same transaction.
 *
 *   WHY: a participant whose team is no longer assigned becomes an
 *   orphan. The participant record still carries a teamId, but no
 *   code path that groups participants by team can resolve it.
 *   Downstream consumers that expect one `members` array per
 *   assigned team end up asking a group for its `.members` and
 *   getting `undefined`, which surfaces as a validation error on
 *   the next save.
 *
 *   Rookie participants (teamId === null) are not affected: they
 *   are not attached to a team and survive the prune.
 *
 *   The prune is silent: no error, no warning. It is the correct
 *   domain behaviour, not a repair. Removing a team from a mission
 *   necessarily removes that team's participants from the mission.
 *
 * REPORTS:
 *   Reports are historical notes attached to a mission. They can be
 *   added, edited, and (soft) removed at any time, independent of
 *   mission status. An edited report carries `updatedAt`; a fresh
 *   report leaves `updatedAt` null until first edit. Removed
 *   reports are dropped from the array entirely.
 *
 * MISSION LOG HAS BEEN REMOVED:
 *   Earlier versions of this module exposed an addLog(missionId,
 *   message) mutation that appended a { timestamp, message } entry
 *   to a `log` array on the mission record, and createMission
 *   seeded that array with an empty list.
 *
 *   That field is gone. Reasons:
 *
 *     - only user-authored entries ever reached it, because no
 *       mutation appended to it automatically;
 *     - the global ActivityLog already covers the audit-trail
 *       use case;
 *     - for a single-user store, an empty per-mission audit trail
 *       is dead weight and a populated one is noise.
 *
 *   A stored mission that still carries `log` keeps it in storage
 *   until the record is next written, at which point
 *   MissionSchema.canonicaliseMissionShape drops it. Nothing in
 *   this module touches the field.
 *
 * DERIVED FIELDS:
 *   progress and pay are recomputed from the candidate inside
 *   validate, via MissionRules.recalculateDerivedFields. The stored
 *   values the user supplied for those fields are ignored; they are
 *   always derived. completedAt is set by the transition rule for
 *   status changes that enter or leave 'completed'.
 *
 * DATE DEFAULTS:
 *   When year, month, or day are absent at creation, the fallback
 *   is: year -> current calendar year, month -> 1, day -> 1. The
 *   form layer supplies its own defaults for the UI; this fallback
 *   exists for programmatic callers.
 *
 * CASCADE HELPER:
 *   stripCharacterRefs delegates to MissionCascade.stripCharacterRefs,
 *   which owns the reference model (supportPersonnel,
 *   reports[].authorId, participants[].characterId). The delegation
 *   exists so that the cross-domain cascade coordinator can reach
 *   every domain's cascade helper through the domain's mutation
 *   module by convention, without the coordinator having to know
 *   each domain's internal module layout.
 *
 * DEPENDENCIES (MANDATORY):
 *   - window.MutationPipeline
 *   - window.ObjectUtils
 *   - window.IdUtils
 *   - window.MissionConstants
 *   - window.MissionId
 *   - window.MissionSchema
 *   - window.MissionRules
 *
 * DEPENDENCIES (LAZY):
 *   - window.MissionCascade   (used only by stripCharacterRefs)
 */

