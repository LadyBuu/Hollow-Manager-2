    // ============================================================
    // PARTICIPANT COMMANDS
    // ============================================================
    //
    // Sub-mutations. Do NOT re-validate the whole mission.
    //
    // addParticipant(missionId, characterId, teamId)
    //   - characterId must normalise
    //   - teamId may be a valid id (source 'team') or null /
    //     undefined / '' (source 'rookie')
    //   - the resolved source comes from
    //     MissionRules.resolveParticipantSource
    //   - the (characterId, teamId) pair must not already exist on
    //     the mission, per MissionRules.hasParticipant
    //   - the assembled participant record must pass
    //     MissionSchema.validateParticipant
    //
    // removeParticipant(missionId, characterId, teamId)
    //   - characterId must normalise
    //   - teamId may be a valid id or null / undefined / ''
    //   - the pair must exist on the mission
    //
    // Neither command checks that the character exists, that the
    // team exists, or that the character was a member of the team.
    // Those are cross-domain concerns. The mission domain trusts
    // the caller to supply well-formed ids.

    function addParticipant(missionId, characterId, teamId) {
        var target = normaliseId(missionId);
        var charTarget = normaliseId(characterId);

        if (target === null) {
            return Promise.resolve(failure('Mission ID is required.'));
        }
        if (charTarget === null) {
            return Promise.resolve(failure('Character ID is required.'));
        }

        // Normalise teamId. Absent, null, or '' all mean 'rookie'.
        // A present value must be a valid id.
        var teamTarget = null;
        var hasTeam = teamId !== undefined &&
                      teamId !== null &&
                      teamId !== '';

        if (hasTeam) {
            teamTarget = normaliseId(teamId);
            if (teamTarget === null) {
                return Promise.resolve(
                    failure('Team ID must be a valid identifier or null.')
                );
            }
        }

        var source = MissionRules.resolveParticipantSource(teamTarget);

        return MutationPipeline.performMutation({
            validate: function(appData) {
                var current = findMissionInSnapshot(appData, target);
                if (!current) {
                    return {
                        valid: false,
                        message: 'Mission no longer exists.'
                    };
                }

                var participants = Array.isArray(current.participants)
                    ? current.participants
                    : [];

                if (MissionRules.hasParticipant(
                    current, charTarget, teamTarget
                )) {
                    return {
                        valid: false,
                        message: 'Character is already a participant ' +
                            'for this ' +
                            (source === 'team' ? 'team.' : 'rookie slot.')
                    };
                }

                // Assemble the new participant and check its shape
                // against the schema's nested validator. This
                // catches the (characterId, teamId, source)
                // coherence rules, not just the pair uniqueness.
                var newParticipant = {
                    characterId: charTarget,
                    teamId: teamTarget,
                    source: source
                };

                var pCheck = validateSingleParticipant(newParticipant);
                if (!pCheck.valid) {
                    return {
                        valid: false,
                        message: pCheck.message
                    };
                }

                var nowIso = new Date().toISOString();
                var candidate = deepClone(current);
                candidate.participants = participants.concat([
                    newParticipant
                ]);
                var final = finaliseCandidate(candidate, nowIso);
                final.completedAt = candidate.completedAt;

                stagedCandidate = final;
                return { valid: true };
            },
            mutate: function(appData) {
                var idx = findMissionIndexInSnapshot(appData, target);
                if (idx === -1) {
                    throw new Error('Mission no longer exists.');
                }
                appData.missions[idx] = deepClone(stagedCandidate);
                return { id: target, mission: stagedCandidate };
            },
            logMessage: function(result) {
                return 'Added ' + source + ' participant to mission: ' +
                    (result.mission.title || target);
            },
            successMessage: 'Participant added.',
            failureMessage: 'Failed to add participant.'
        });
    }

