    function isPlainObject(value) {
        return value !== null &&
               typeof value === 'object' &&
               !Array.isArray(value);
    }

    function isNonEmptyString(value) {
        return typeof value === 'string' && value.trim() !== '';
    }

    function normaliseId(value) {
        return IdUtils.normaliseId(value);
    }

    function generateId(prefix) {
        return IdUtils.generateId(prefix);
    }

    function deepClone(value) {
        var result = ObjectUtils.deepClone(value);
        if (result === value &&
            value !== null &&
            typeof value === 'object') {
            throw new Error(
                '[MissionCore] deepClone returned the original reference.'
            );
        }
        return result;
    }

    function failure(message) {
        return { success: false, message: message };
    }

    function success(data) {
        return { success: true, data: data };
    }

    // ============================================================
    // SNAPSHOT ACCESS
    // ============================================================
    //
    // Reads from the appData snapshot the pipeline hands in. Never
    // touches window.data.

    function ensureMissionArray(appData) {
        if (!appData || typeof appData !== 'object') {
            return null;
        }
        if (!Array.isArray(appData.missions)) {
            appData.missions = [];
        }
        return appData.missions;
    }

    function findMissionInSnapshot(appData, missionId) {
        if (!appData || !Array.isArray(appData.missions)) {
            return null;
        }
        var target = normaliseId(missionId);
        if (target === null) { return null; }
        var missions = appData.missions;
        for (var i = 0; i < missions.length; i++) {
            var m = missions[i];
            if (isPlainObject(m) && normaliseId(m.id) === target) {
                return m;
            }
        }
        return null;
    }

    function findMissionIndexInSnapshot(appData, missionId) {
        if (!appData || !Array.isArray(appData.missions)) {
            return -1;
        }
        var target = normaliseId(missionId);
        if (target === null) { return -1; }
        var missions = appData.missions;
        for (var i = 0; i < missions.length; i++) {
            var m = missions[i];
            if (isPlainObject(m) && normaliseId(m.id) === target) {
                return i;
            }
        }
        return -1;
    }

    // ============================================================
    // CANDIDATE FINALISATION
    // ============================================================
    //
    // After applying any updates to a mission candidate, recompute
    // derived fields from the candidate's own facts and preserve the
    // completedAt the caller computed.

    function finaliseCandidate(candidate, nowIso) {
        var recalculated = MissionRules.recalculateDerivedFields(candidate);
        recalculated.completedAt = candidate.completedAt;
        return recalculated;
    }

    // ============================================================
    // PARTICIPANT PRUNE ON TEAM REMOVAL
    // ============================================================
    //
    // When assignedTeamIds shrinks, any participant whose teamId
    // points at a removed team becomes an orphan. Prune it from
    // the candidate in the same transaction.
    //
    // Rookie participants (teamId === null) are not affected.
    //
    // The prune is silent and unconditional. It does not depend on
    // whether the caller knew about the participants; removing a
    // team from a mission is, by definition, removing that team's
    // participants from the mission.

    function pruneOrphanedParticipants(candidate) {
        if (!Array.isArray(candidate.participants)) {
            return;
        }
        if (!Array.isArray(candidate.assignedTeamIds)) {
            return;
        }

        var assignedSet = Object.create(null);
        for (var i = 0; i < candidate.assignedTeamIds.length; i++) {
            var norm = normaliseId(candidate.assignedTeamIds[i]);
            if (norm !== null) {
                assignedSet[norm] = true;
            }
        }

        candidate.participants = candidate.participants.filter(
            function(p) {
                if (!isPlainObject(p)) { return true; }

                // Rookie participants are not attached to a team.
                if (p.teamId === null || p.teamId === undefined) {
                    return true;
                }

                var tid = normaliseId(p.teamId);
                return tid !== null && assignedSet[tid] === true;
            }
        );
    }

    // ============================================================
    // NESTED VALIDATION HELPERS
    // ============================================================

    function validateSingleReport(report) {
        var errors = [];
        MissionSchema.validateReport(report, 0, errors);
        return {
            valid: errors.length === 0,
            message: errors.join('; ')
        };
    }

    function validateSingleParticipant(participant) {
        var errors = [];
        MissionSchema.validateParticipant(participant, 0, errors);
        return {
            valid: errors.length === 0,
            message: errors.join('; ')
        };
    }

    // ============================================================
    // CREATE
    // ============================================================

    /**
     * Create a new mission.
     *
     * Required: title. Optional: id. When id is absent, a fresh id
     * is generated with the 'miss' prefix. When present and valid,
     * the mission uses the supplied id; a collision with an
     * existing mission id is rejected by the pipeline's validate
     * step.
     *
     * Everything else falls back to MissionConstants.getDefaults()
     * for enum fields, to '' / [] / null for text, arrays, and IDs,
     * and to (currentYear, 1, 1) for absent date components.
     *
     * The created mission has NO `log` field. See the file header.
     *
     * @returns {Promise<{success, data?, message?}>}
     */
    function createMission(data) {
        if (!isPlainObject(data)) {
            return Promise.resolve(
                failure('Mission data is required.')
            );
        }
        if (!isNonEmptyString(data.title)) {
            return Promise.resolve(
                failure('Mission title is required.')
            );
        }

        // ---- Pre-resolve the requested id, if any ----
        //
        // A caller that supplies an id must supply a valid one.
        // Falling back to a generated id would silently produce a
        // record the caller did not ask for. So an invalid supplied
        // id is a hard rejection, not a silent substitution.
        //
        // Absence of the id parameter (undefined, null, '') means
        // "generate one." That is the historical behaviour.
        var requestedId = null;
        var hasRequestedId = data.id !== undefined &&
                             data.id !== null &&
                             data.id !== '';

        if (hasRequestedId) {
            requestedId = normaliseId(data.id);
            if (requestedId === null) {
                return Promise.resolve(failure(
                    'Supplied id is not a valid identifier.'
                ));
            }
        }

        return MutationPipeline.performMutation({
            validate: function(appData) {
                if (!appData || typeof appData !== 'object') {
                    return {
                        valid: false,
                        message: 'Application data is not available.'
                    };
                }

                var missions = ensureMissionArray(appData);
                if (!missions) {
                    return {
                        valid: false,
                        message: 'Mission store is not available.'
                    };
                }

                // ---- Resolve the candidate id ----
                var candidateId;
                if (requestedId !== null) {
                    if (findMissionInSnapshot(appData, requestedId)) {
                        return {
                            valid: false,
                            message: 'A mission with id "' +
                                requestedId + '" already exists.'
                        };
                    }
                    candidateId = requestedId;
                } else {
                    candidateId = generateId('miss');
                }

                var defaults = MissionConstants.getDefaults();
                var nowIso = new Date().toISOString();
                var now = new Date();

                var raw = {
                    id: candidateId,

                    title: typeof data.title === 'string'
                        ? data.title.trim()
                        : '',

                    description: typeof data.description === 'string'
                        ? data.description
                        : '',

                    year: data.year !== undefined && data.year !== null
                        ? data.year
                        : now.getFullYear(),

                    month: data.month !== undefined && data.month !== null
                        ? data.month
                        : 1,

                    day: data.day !== undefined && data.day !== null
                        ? data.day
                        : 1,

                    primaryType: typeof data.primaryType === 'string'
                        ? data.primaryType
                        : '',

                    subtype: typeof data.subtype === 'string'
                        ? data.subtype
                        : '',

                    secondaryType: typeof data.secondaryType === 'string'
                        ? data.secondaryType
                        : '',

                    escalation: data.escalation !== undefined &&
                                data.escalation !== null
                        ? data.escalation
                        : defaults.escalation,

                    threatType: typeof data.threatType === 'string'
                        ? data.threatType
                        : '',

                    environment: typeof data.environment === 'string'
                        ? data.environment
                        : '',

                    location: typeof data.location === 'string'
                        ? data.location
                        : '',

                    duration: typeof data.duration === 'string'
                        ? data.duration
                        : '',

                    difficulty: data.difficulty !== undefined &&
                                data.difficulty !== null
                        ? data.difficulty
                        : defaults.difficulty,

                    priority: data.priority !== undefined &&
                              data.priority !== null
                        ? data.priority
                        : defaults.priority,

                    basePay: typeof data.basePay === 'string'
                        ? data.basePay
                        : '',

                    surchargePay: typeof data.surchargePay === 'string'
                        ? data.surchargePay
                        : '',

                    pay: '',

                    billing: data.billing !== undefined &&
                             data.billing !== null
                        ? data.billing
                        : defaults.billing,

                    assignedTeamIds: Array.isArray(data.assignedTeamIds)
                        ? data.assignedTeamIds.slice()
                        : [],

                    supportPersonnel: Array.isArray(data.supportPersonnel)
                        ? data.supportPersonnel.slice()
                        : [],

                    participants: Array.isArray(data.participants)
                        ? data.participants.map(function(p) {
                            if (!isPlainObject(p)) { return p; }
                            return {
                                characterId: p.characterId,
                                teamId: p.teamId !== undefined
                                    ? p.teamId
                                    : null,
                                source: p.source
                            };
                        })
                        : [],

                    status: data.status !== undefined &&
                            data.status !== null
                        ? data.status
                        : defaults.status,

                    objectives: Array.isArray(data.objectives)
                        ? data.objectives.map(function(obj) {
                            return {
                                text: obj && typeof obj.text === 'string'
                                    ? obj.text
                                    : '',
                                done: obj && obj.done === true
                            };
                        })
                        : [],

                    progress: 0,

                    notes: typeof data.notes === 'string'
                        ? data.notes
                        : '',

                    tags: Array.isArray(data.tags)
                        ? data.tags.slice()
                        : [],

                    createdAt: nowIso,
                    completedAt: null,
                    archivedAt: null,

                    reports: [],

                    graduatingClassId: data.graduatingClassId !== undefined
                        ? data.graduatingClassId
                        : null,

                    classFilterEnabled:
                        data.classFilterEnabled === true
                };

                // Sequence is scoped to (year, difficulty). The
                // generator walks the snapshot missions and returns
                // max(sequence) + 1 for that scope.
                var sequenceResult = MissionId.generate(
                    raw.year,
                    raw.difficulty,
                    missions
                );
                if (!sequenceResult) {
                    return {
                        valid: false,
                        message:
                            'Could not allocate a mission sequence for ' +
                            'the given year and difficulty.'
                    };
                }
                raw.sequence = sequenceResult.sequence;

                var canonical = MissionSchema.canonicaliseMissionShape(raw);
                if (!canonical.valid || !canonical.value) {
                    return {
                        valid: false,
                        message: canonical.errors.join('; ')
                    };
                }

                var candidate = finaliseCandidate(
                    canonical.value,
                    nowIso
                );

                var validated = MissionSchema.validateMission(candidate);
                if (!validated.valid) {
                    return {
                        valid: false,
                        message: validated.errors.join('; ')
                    };
                }

                stagedCandidate = candidate;

                return { valid: true };
            },

            mutate: function(appData) {
                var missions = ensureMissionArray(appData);
                if (!missions) {
                    throw new Error(
                        'Mission store is not available.'
                    );
                }

                if (!stagedCandidate) {
                    throw new Error(
                        'Mission candidate was not built during validate.'
                    );
                }

                missions.push(deepClone(stagedCandidate));

                return {
                    mission: stagedCandidate,
                    id: stagedCandidate.id
                };
            },

            logMessage: function(result) {
                return 'Created mission: ' + result.mission.title;
            },
            successMessage: 'Mission created.',
            failureMessage: 'Failed to create mission.'
        });
    }

    // ============================================================
    // UPDATE
    // ============================================================

    /**
     * Update an existing mission.
     *
     * Updatable fields: every non-derived, non-timestamp field.
     * id, sequence, createdAt are never changed by this function.
     * Status changes go through the status-transition rules.
     *
     * This is one of the two operations that runs the whole-record
     * MissionSchema.validateMission, because the caller supplies
     * structural fields (title, difficulty, subtype, ...).
     *
     * When `assignedTeamIds` is provided, participants whose teamId
     * points at a team that is no longer in the new array are
     * pruned from the candidate in the same transaction. See
     * pruneOrphanedParticipants above for the reasoning.
     *
     * A legacy `log` field on the stored record is dropped by the
     * canonicaliser, because updateMission feeds the candidate
     * through canonicaliseMissionShape. Nothing here touches it.
     *
     * @returns {Promise<{success, data?, message?}>}
     */
    function updateMission(missionId, updates) {
        var target = normaliseId(missionId);
        if (target === null) {
            return Promise.resolve(failure('Mission ID is required.'));
        }
        if (!isPlainObject(updates) || Object.keys(updates).length === 0) {
            return Promise.resolve(
                failure('Updates must be a non-empty object.')
            );
        }

        return MutationPipeline.performMutation({
            validate: function(appData) {
                if (!appData || typeof appData !== 'object') {
                    return {
                        valid: false,
                        message: 'Application data is not available.'
                    };
                }

                var current = findMissionInSnapshot(appData, target);
                if (!current) {
                    return {
                        valid: false,
                        message: 'Mission no longer exists.'
                    };
                }

                var nowIso = new Date().toISOString();
                var candidate = deepClone(current);

                // Status change runs against the CURRENT status so
                // the transition rule sees the real "from".
                if (updates.status !== undefined &&
                    updates.status !== current.status) {
                    var statusCheck = MissionRules.validateStatusChange(
                        current,
                        updates.status
                    );
                    if (!statusCheck.valid) {
                        return statusCheck;
                    }
                    candidate.status = updates.status;
                    candidate.completedAt = MissionRules.deriveCompletedAt(
                        current.status,
                        updates.status,
                        current.completedAt,
                        nowIso
                    );
                }

                if (updates.objectives !== undefined) {
                    if (!Array.isArray(updates.objectives)) {
                        return {
                            valid: false,
                            message: 'Objectives must be an array.'
                        };
                    }
                    var objCheck = MissionRules.validateObjectivesEditable(
                        current
                    );
                    if (!objCheck.valid) {
                        return objCheck;
                    }
                    candidate.objectives = updates.objectives.map(
                        function(obj) {
                            return {
                                text: obj && typeof obj.text === 'string'
                                    ? obj.text
                                    : '',
                                done: obj && obj.done === true
                            };
                        }
                    );
                }

                if (updates.supportPersonnel !== undefined) {
                    if (!Array.isArray(updates.supportPersonnel)) {
                        return {
                            valid: false,
                            message: 'Support personnel must be an array.'
                        };
                    }
                    candidate.supportPersonnel =
                        updates.supportPersonnel.slice();
                }

                if (updates.participants !== undefined) {
                    if (!Array.isArray(updates.participants)) {
                        return {
                            valid: false,
                            message: 'Participants must be an array.'
                        };
                    }
                    candidate.participants = updates.participants.map(
                        function(p) {
                            if (!isPlainObject(p)) { return p; }
                            return {
                                characterId: p.characterId,
                                teamId: p.teamId !== undefined
                                    ? p.teamId
                                    : null,
                                source: p.source
                            };
                        }
                    );
                }

                if (updates.assignedTeamIds !== undefined) {
                    if (!Array.isArray(updates.assignedTeamIds)) {
                        return {
                            valid: false,
                            message: 'Assigned teams must be an array.'
                        };
                    }
                    candidate.assignedTeamIds =
                        updates.assignedTeamIds.slice();

                    // Removing a team from a mission must also
                    // remove that team's participants. Otherwise
                    // the participant list carries orphans whose
                    // teamId no longer resolves to an assigned
                    // team, and any consumer that groups
                    // participants by team produces a group with
                    // no `members` array. See the file header.
                    //
                    // Rookie participants (teamId === null) are
                    // not affected.
                    pruneOrphanedParticipants(candidate);
                }

                copyIfProvided(
                    candidate, updates, 'title',
                    function(v) {
                        return typeof v === 'string' ? v.trim() : v;
                    }
                );
                copyIfProvided(candidate, updates, 'description');
                copyIfProvided(candidate, updates, 'primaryType');
                copyIfProvided(candidate, updates, 'subtype');
                copyIfProvided(candidate, updates, 'secondaryType');
                copyIfProvided(candidate, updates, 'escalation');
                copyIfProvided(candidate, updates, 'threatType');
                copyIfProvided(candidate, updates, 'environment');
                copyIfProvided(candidate, updates, 'location');
                copyIfProvided(candidate, updates, 'duration');
                copyIfProvided(candidate, updates, 'difficulty');
                copyIfProvided(candidate, updates, 'priority');
                copyIfProvided(candidate, updates, 'basePay');
                copyIfProvided(candidate, updates, 'surchargePay');
                copyIfProvided(candidate, updates, 'billing');
                copyIfProvided(candidate, updates, 'notes');
                copyIfProvided(candidate, updates, 'tags');
                copyIfProvided(candidate, updates, 'graduatingClassId');
                copyIfProvided(candidate, updates, 'classFilterEnabled');
                copyIfProvided(candidate, updates, 'year');
                copyIfProvided(candidate, updates, 'month');
                copyIfProvided(candidate, updates, 'day');

                var final = finaliseCandidate(candidate, nowIso);
                final.completedAt = candidate.completedAt;

                var validated = MissionSchema.validateMission(final);
                if (!validated.valid) {
                    return {
                        valid: false,
                        message: validated.errors.join('; ')
                    };
                }

                stagedCandidate = final;
                return { valid: true };
            },

            mutate: function(appData) {
                var idx = findMissionIndexInSnapshot(appData, target);
                if (idx === -1) {
                    throw new Error(
                        'Mission disappeared between validate and mutate.'
                    );
                }

                if (!stagedCandidate) {
                    throw new Error(
                        'Mission candidate was not built during validate.'
                    );
                }

                appData.missions[idx] = deepClone(stagedCandidate);

                return {
                    mission: stagedCandidate,
                    id: target
                };
            },

            logMessage: function(result) {
                return 'Updated mission: ' +
                    (result.mission.title || target);
            },
            successMessage: 'Mission updated.',
            failureMessage: 'Failed to update mission.'
        });
    }

